//! Synthesizable SystemC emitter for the typed `svcc_ir::hdl` design IR.
//!
//! Mapping (two-state, IEEE 1666-2023 data types, IEEE 1666.1 synthesizable style):
//!
//! - module -> `SC_MODULE`, ports -> `sc_in` / `sc_out`, variables and nets -> `sc_signal`,
//!   unpacked arrays -> `sc_vector<sc_signal<T>>`.
//! - 1-bit scalars -> `bool`; vectors up to 64 bits -> `sc_uint<W>` / `sc_int<W>`; wider
//!   vectors -> `sc_biguint<W>` / `sc_bigint<W>`.
//! - combinational processes -> `SC_METHOD` sensitive to every signal read; edge-triggered
//!   processes -> `SC_METHOD` sensitive to the same edges as the source block, with the body
//!   translated statement by statement.
//! - blocking assignments use a local copy of the target that is written back once at the end
//!   of the process, so a value assigned earlier in the block is visible to later statements
//!   exactly as in the source language. Nonblocking assignments write the signal directly.
//!
//! Every expression node in the IR carries its width and signedness. The emitter keeps the
//! invariant that each emitted C++ subexpression evaluates to exactly the value of its IR
//! node, truncating explicitly wherever C++ would compute in a wider type.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write;

use svcc_ir::hdl::{
    BinOp, Design, Dir, Expr, Function, LocalVar, LvBase, Lval, Module, Pat, ProcKind, Process,
    Stmt, Ty, UnOp,
};
use svcc_ir::SvccError;

const STAGE: &str = "svcc-emit-sc/hdl";

/// Emits a complete, self-contained SystemC header for `design`.
pub fn emit_hdl_design(design: &Design) -> Result<String, SvccError> {
    let mut out = String::new();
    out.push_str("#pragma once\n");
    out.push_str(
        "// Generated by svcc: synthesizable SystemC (IEEE 1666-2023 data types, IEEE 1666.1 subset).\n",
    );
    out.push_str("// Two-state model: x and z in the source map to 0.\n");
    out.push_str("#include <cstdint>\n#include <systemc>\n\n");
    emit_hdl_modules(&mut out, design)?;
    Ok(out)
}

/// Emits only the `SC_MODULE` definitions of `design` (no includes).
pub fn emit_hdl_modules(out: &mut String, design: &Design) -> Result<(), SvccError> {
    let mut errs = Vec::new();
    for m in &design.modules {
        let mut em = Em {
            m,
            design,
            errs: Vec::new(),
            fn_reads: HashMap::new(),
        };
        em.module(out);
        errs.extend(em.errs);
    }
    if errs.is_empty() {
        Ok(())
    } else {
        Err(SvccError::new(STAGE, errs.join("\n  ")))
    }
}

