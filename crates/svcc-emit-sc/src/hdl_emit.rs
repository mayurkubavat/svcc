    // Statements
    // ------------------------------------------------------------------

    fn stmts(
        &mut self,
        out: &mut String,
        stmts: &[Stmt],
        env: &mut Env,
        ind: &str,
        ret: Option<Ty>,
    ) {
        for s in stmts {
            self.stmt(out, s, env, ind, ret);
        }
    }

    fn stmt(&mut self, out: &mut String, s: &Stmt, env: &mut Env, ind: &str, ret: Option<Ty>) {
        let ind2 = format!("{ind}  ");
        match s {
            Stmt::Assign {
                lhs,
                rhs,
                nonblocking,
            } => self.assign(out, lhs, rhs, *nonblocking, env, ind),
            Stmt::If {
                cond,
                then_s,
                else_s,
            } => {
                let c = self.ex(cond, env);
                let _ = writeln!(out, "{ind}if ({}) {{", strip_parens(&self.truthy(c)));
                self.stmts(out, then_s, env, &ind2, ret);
                let mut rest: &[Stmt] = else_s;
                // Keep `else if` chains flat.
                loop {
                    match rest {
                        [] => {
                            let _ = writeln!(out, "{ind}}}");
                            break;
                        }
                        [Stmt::If {
                            cond,
                            then_s,
                            else_s,
                        }] => {
                            let c = self.ex(cond, env);
                            let _ = writeln!(
                                out,
                                "{ind}}} else if ({}) {{",
                                strip_parens(&self.truthy(c))
                            );
                            self.stmts(out, then_s, env, &ind2, ret);
                            rest = else_s;
                        }
                        other => {
                            let _ = writeln!(out, "{ind}}} else {{");
                            self.stmts(out, other, env, &ind2, ret);
                            let _ = writeln!(out, "{ind}}}");
                            break;
                        }
                    }
                }
            }
            Stmt::Case { sel, arms, default } => self.case(out, sel, arms, default, env, ind, ret),
            Stmt::For {
                init,
                cond,
                step,
                body,
            } => {
                let simple = |ss: &[Stmt]| {
                    ss.iter().all(|s| {
                        matches!(
                            s,
                            Stmt::Assign {
                                lhs: Lval {
                                    base: LvBase::Local { .. },
                                    sel: None
                                },
                                ..
                            }
                        )
                    })
                };
                let range = loop_range(init, cond, step, body);
                let inline = simple(init) && simple(step);
                let mut init_code = String::new();
                if inline {
                    init_code = self.inline_assigns(init, env);
                } else {
                    self.stmts(out, init, env, ind, ret);
                }
                if let Some((name, lo, hi)) = &range {
                    env.ranges.insert(name.clone(), (*lo, *hi));
                }
                let c = self.ex(cond, env);
                let cond_code = strip_parens(&self.truthy(c)).to_string();
                if inline {
                    let step_code = self.inline_assigns(step, env);
                    let _ = writeln!(out, "{ind}for ({init_code}; {cond_code}; {step_code}) {{");
                    self.stmts(out, body, env, &ind2, ret);
                } else {
                    let _ = writeln!(out, "{ind}for (; {cond_code}; ) {{");
                    self.stmts(out, body, env, &ind2, ret);
                    self.stmts(out, step, env, &ind2, ret);
                }
                let _ = writeln!(out, "{ind}}}");
                if let Some((name, _, _)) = &range {
                    env.ranges.remove(name);
                }
            }
            Stmt::Return(e) => {
                let Some(rt) = ret else {
                    self.err("return outside a function");
                    return;
                };
                let v = self.ex(e, env);
                let _ = writeln!(out, "{ind}return {};", self.to_local(v, rt));
            }
            Stmt::Block { locals, body } => {
                let _ = writeln!(out, "{ind}{{");
                self.locals(out, locals, &ind2);
                self.stmts(out, body, env, &ind2, ret);
                let _ = writeln!(out, "{ind}}}");
            }
        }
    }

    /// `a = x, b = y` form of local assignments, for `for` headers.
    fn inline_assigns(&mut self, ss: &[Stmt], env: &mut Env) -> String {
        let mut parts = Vec::new();
        for s in ss {
            if let Stmt::Assign {
                lhs:
                    Lval {
                        base: LvBase::Local { name, ty },
                        ..
                    },
                rhs,
                ..
            } = s
            {
                let v = self.ex(rhs, env);
                parts.push(format!(
                    "{} = {}",
                    cname(name),
                    strip_parens(&self.to_local(v, *ty))
                ));
            }
        }
        parts.join(", ")
    }

    #[allow(clippy::too_many_arguments)]
    fn case(
        &mut self,
        out: &mut String,
        sel: &Expr,
        arms: &[svcc_ir::hdl::CaseArm],
        default: &Option<Vec<Stmt>>,
        env: &mut Env,
        ind: &str,
        ret: Option<Ty>,
    ) {
        let ty = sel.ty();
        let ind2 = format!("{ind}  ");
        let ind3 = format!("{ind}    ");
        let full = ty.w <= 64
            && arms.iter().all(|a| {
                a.pats.iter().all(|p| match p {
                    Pat::Const { care, .. } => care[0] == mask64(ty.w),
                    Pat::Expr(_) => false,
                })
            });
        let mut seen = BTreeSet::new();
        let distinct = arms.iter().all(|a| {
            a.pats.iter().all(|p| match p {
                Pat::Const { value, .. } => seen.insert(value[0]),
                Pat::Expr(_) => false,
            })
        });
        if full && distinct && !arms.is_empty() {
            let s = self.ex(sel, env);
            let bits = self.bits(s, ty);
            let _ = writeln!(out, "{ind}switch (uint64_t({})) {{", strip_parens(&bits));
            for a in arms {
                for p in &a.pats {
                    if let Pat::Const { value, .. } = p {
                        let _ = writeln!(out, "{ind2}case {}:", value[0]);
                    }
                }
                self.stmts(out, &a.body, env, &ind3, ret);
                let _ = writeln!(out, "{ind3}break;");
            }
            let _ = writeln!(out, "{ind2}default:");
            if let Some(d) = default {
                self.stmts(out, d, env, &ind3, ret);
            }
            let _ = writeln!(out, "{ind3}break;");
            let _ = writeln!(out, "{ind}}}");
            return;
        }
        // Priority chain on a single evaluation of the selector.
        env.depth += 1;
        let tmp = format!("_sel{}", env.depth);
        let uty = Ty::unsigned(ty.w);
        let s = self.ex(sel, env);
        let bits = self.bits(s, ty);
        let _ = writeln!(out, "{ind}{{");
        let _ = writeln!(
            out,
            "{ind2}const {} {} = {};",
            sc_ty(uty),
            tmp,
            strip_parens(&bits)
        );
        let mut first = true;
        for a in arms {
            let mut tests = Vec::new();
            for p in &a.pats {
                match p {
                    Pat::Const { value, care } => {
                        let v = self.konst(uty, value);
                        let v = if uty.w > 64 {
                            self.to_sc(v, uty)
                        } else {
                            v.code
                        };
                        let all = care
                            .iter()
                            .enumerate()
                            .all(|(i, c)| *c == mask64(uty.w.saturating_sub(64 * i as u32)));
                        if all {
                            tests.push(format!("{tmp} == {v}"));
                        } else {
                            let c = self.konst(uty, care);
                            let c = if uty.w > 64 {
                                self.to_sc(c, uty)
                            } else {
                                c.code
                            };
                            tests.push(format!("({tmp} & {c}) == {v}"));
                        }
                    }
                    Pat::Expr(e) => {
                        let v = self.ex(e, env);
                        let b = self.bits(v, ty);
                        tests.push(format!("{tmp} == {b}"));
                    }
                }
            }
            let kw = if first { "if" } else { "} else if" };
            first = false;
            let _ = writeln!(out, "{ind2}{kw} ({}) {{", tests.join(" || "));
            self.stmts(out, &a.body, env, &ind3, ret);
        }
        match default {
            Some(d) if !d.is_empty() => {
                if first {
                    self.stmts(out, d, env, &ind2, ret);
                } else {
                    let _ = writeln!(out, "{ind2}}} else {{");
                    self.stmts(out, d, env, &ind3, ret);
                    let _ = writeln!(out, "{ind2}}}");
                }
            }
            _ => {
                if !first {
                    let _ = writeln!(out, "{ind2}}}");
                }
            }
        }
        let _ = writeln!(out, "{ind}}}");
        env.depth -= 1;
    }

    fn assign(
        &mut self,
        out: &mut String,
        lhs: &Lval,
        rhs: &Expr,
        nonblocking: bool,
        env: &mut Env,
        ind: &str,
    ) {
        let r = self.ex(rhs, env);
        let bty = lhs.base.ty();
        // Resolve the storage being written.
        // `var`: a C++ variable (local, or local copy of a signal); `sig`: a signal to `.write`.
        let mut guard: Vec<String> = Vec::new();
        let (var, sig, scalar): (Option<String>, Option<String>, bool) = match &lhs.base {
            LvBase::Local { name, ty } => (Some(cname(name)), None, *ty == Ty::BIT),
            LvBase::Sig { name, .. } => {
                let scalar = self.sig_scalar(name);
                let copy = if nonblocking {
                    env.next.get(name)
                } else {
                    env.cur.get(name)
                };
                match copy {
                    Some(c) => (Some(c.clone()), None, scalar),
                    None => (None, Some(cname(name)), scalar),
                }
            }
            LvBase::Elem { name, idx, .. } => {
                let scalar = self.sig_scalar(name);
                let ix = self.elem_index(name, idx, env, &mut guard);
                let copy = if nonblocking {
                    env.next.get(name)
                } else {
                    env.cur.get(name)
                };
                match copy {
                    Some(c) => (Some(format!("{c}[{ix}]")), None, scalar),
                    None => (None, Some(format!("{}[{}]", cname(name), ix)), scalar),
                }
            }
        };
        let is_native_local = matches!(&lhs.base, LvBase::Local { ty, .. } if *ty == Ty::INT);

        let stmt = match &lhs.sel {
            None => {
                let value = if scalar {
                    self.to_bool(r)
                } else if is_native_local {
                    strip_parens(&self.to_local(r, bty)).to_string()
                } else {
                    self.to_sc(r, bty)
                };
                match (&var, &sig) {
                    (Some(v), _) => format!("{v} = {};", strip_parens(&value)),
                    (None, Some(s)) => format!("{s}.write({});", strip_parens(&value)),
                    _ => return,
                }
            }
            Some(sel) => {
                let Some(v) = &var else {
                    self.err(format!(
                        "partial assignment to '{}' without a local copy",
                        lhs.base.name()
                    ));
                    return;
                };
                if scalar || is_native_local {
                    // A 1-bit variable has a single bit to select.
                    format!("{v} = {};", strip_parens(&self.to_bool(r)))
                } else {
                    let value = if sel.w == 1 {
                        self.to_bool(r)
                    } else if sel.w > 64 {
                        self.to_sc(r, Ty::unsigned(sel.w))
                    } else {
                        r.code
                    };
                    let value = strip_parens(&value).to_string();
                    match &sel.lo_dyn {
                        None => {
                            if sel.w == 1 {
                                format!("{v}[{}] = {value};", sel.lo)
                            } else {
                                format!("{v}.range({}, {}) = {value};", sel.lo + sel.w - 1, sel.lo)
                            }
                        }
                        Some(d) => {
                            let dv = self.ex(d, env);
                            let pos = if sel.lo == 0 {
                                dv.code
                            } else {
                                format!("({} + {})", dv.code, sel.lo)
                            };
                            let max_lo = bty.w as i128 - sel.w as i128 - sel.lo as i128;
                            let safe = self
                                .rng(d, env)
                                .is_some_and(|(lo, hi)| lo >= -(sel.lo as i128) && hi <= max_lo);
                            let p = if safe {
                                pos
                            } else {
                                // Only the bits that fall inside the target are written.
                                let p = format!("_p{}", env.depth + 1);
                                let write = if sel.w == 1 {
                                    format!("if ({p} >= 0 && {p} < {}) {v}[{p}] = {value};", bty.w)
                                } else {
                                    let src = format!(
                                        "const {} _s = {value};",
                                        sc_ty(Ty::unsigned(sel.w))
                                    );
                                    format!(
                                        "{src} for (int _k = 0; _k < {}; ++_k) if ({p} + _k >= 0 && {p} + _k < {}) {v}[{p} + _k] = bool(_s[_k]);",
                                        sel.w, bty.w
                                    )
                                };
                                let line = format!(
                                    "{{ const long long {p} = {}; {write} }}",
                                    strip_parens(&pos)
                                );
                                self.guarded(out, &guard, &line, ind);
                                return;
                            };
                            if sel.w == 1 {
                                format!("{v}[{}] = {value};", strip_parens(&p))
                            } else {
                                format!("{v}.range({p} + {}, {p}) = {value};", sel.w - 1)
                            }
                        }
                    }
                }
            }
        };
        self.guarded(out, &guard, &stmt, ind);
    }

    fn guarded(&mut self, out: &mut String, guard: &[String], stmt: &str, ind: &str) {
        if guard.is_empty() {
            let _ = writeln!(out, "{ind}{stmt}");
        } else {
            let _ = writeln!(out, "{ind}if ({}) {stmt}", guard.join(" && "));
        }
    }

    /// Flat index expression of an array element; pushes range tests that are not provable.
    fn elem_index(
        &mut self,
        name: &str,
        idx: &[Expr],
        env: &mut Env,
        guard: &mut Vec<String>,
    ) -> String {
        let dims = self.sig_dims(name).to_vec();
        let mut flat = String::new();
        for (k, e) in idx.iter().enumerate() {
            let d = dims.get(k).copied().unwrap_or(1);
            let v = self.ex(e, env);
            let code = match const_i128(e) {
                Some(c) => format!("{c}"),
                None => v.code,
            };
            let safe = self
                .rng(e, env)
                .is_some_and(|(lo, hi)| lo >= 0 && hi < d as i128);
            if !safe {
                if e.ty().s {
                    guard.push(format!("{code} >= 0"));
                }
                guard.push(format!("{code} < {d}"));
            }
            flat = if k == 0 {
                code
            } else {
                format!("({flat}) * {d} + {code}")
            };
        }
        flat
    }

    // ------------------------------------------------------------------
    // Value conversions
    // ------------------------------------------------------------------

    /// Expression of exactly the SystemC type of `ty`.
    fn to_sc(&self, v: Val, ty: Ty) -> String {
        if v.rep == Rep::Sc {
            v.code
        } else {
            format!("{}({})", sc_ty(ty), strip_parens(&v.code))
        }
    }

    /// Expression usable as a C++ `bool` (the value is 1 bit).
    fn to_bool(&self, v: Val) -> String {
        match v.rep {
            Rep::Bool | Rep::I32 => v.code,
            _ => format!("bool({})", strip_parens(&v.code)),
        }
    }

    fn truthy(&self, v: Val) -> String {
        match v.rep {
            Rep::Bool => v.code,
            _ => format!("({} != 0)", v.code),
        }
    }

    /// Expression assignable to a local variable of type `ty`.
    fn to_local(&self, v: Val, ty: Ty) -> String {
        if ty == Ty::BIT {
            self.to_bool(v)
        } else if ty == Ty::INT {
            match v.rep {
                Rep::I32 | Rep::Bool => v.code,
                _ => format!("int({})", strip_parens(&v.code)),
            }
        } else {
            self.to_sc(v, ty)
        }
    }

    /// The raw bits of a value as an unsigned SystemC value of the same width.
    fn bits(&self, v: Val, ty: Ty) -> String {
        let u = Ty::unsigned(ty.w);
        if !ty.s {
            self.to_sc(v, u)
        } else {
            format!("{}({})", sc_ty(u), strip_parens(&v.code))
        }
    }

    /// 64-bit operand: small C++ ints are widened when the node is wider than 32 bits.
    fn wide(&self, v: &Val, ty: Ty) -> String {
        if ty.w > 32 && matches!(v.rep, Rep::Bool | Rep::I32) {
            format!(
                "{}({})",
                if ty.s { "int64_t" } else { "uint64_t" },
                strip_parens(&v.code)
            )
        } else {
            v.code.clone()
        }
    }

    fn konst(&mut self, ty: Ty, words: &[u64]) -> Val {
        if ty.w <= 64 {
            let v = words.first().copied().unwrap_or(0);
            if ty == Ty::BIT {
                return val(if v != 0 { "true" } else { "false" }, Rep::Bool);
            }
            if !ty.s {
                let rep = if ty.w <= 32 { Rep::I32 } else { Rep::N64 };
                return val(lit64(v, ty.w), rep);
            }
            let sv: i64 = if ty.w < 64 && (v >> (ty.w - 1)) & 1 == 1 {
                (v as i128 - (1i128 << ty.w)) as i64
            } else {
                v as i64
            };
            if sv == i64::MIN {
                return val("(-9223372036854775807LL - 1)", Rep::N64);
            }
            if ty.w <= 31 || (sv.abs() < (1 << 30) && ty.w <= 32) {
                return val(
                    if sv < 0 {
                        format!("({sv})")
                    } else {
                        format!("{sv}")
                    },
                    Rep::I32,
                );
            }
            return val(
                if sv < 0 {
                    format!("({sv}LL)")
                } else {
                    format!("{sv}LL")
                },
                Rep::N64,
            );
        }
        // Wider than 64 bits.
        let t = sc_ty(ty);
        let hi_zero = words.iter().skip(1).all(|w| *w == 0);
        if hi_zero {
            return val(format!("{t}({})", lit64(words[0], 64)), Rep::Sc);
        }
        let n = ty.w.div_ceil(64) as usize;
        let mut parts = Vec::new();
        for i in (0..n).rev() {
            let w = if i == n - 1 { ty.w - 64 * i as u32 } else { 64 };
            parts.push(format!(
                "sc_dt::sc_uint<{w}>({})",
                lit64(words.get(i).copied().unwrap_or(0), 64)
            ));
        }
        let u = format!("{}(({}))", sc_ty(Ty::unsigned(ty.w)), parts.join(", "));
        if ty.s {
            val(format!("{t}({u})"), Rep::Sc)
        } else {
            val(u, Rep::Sc)
        }
    }

    // ------------------------------------------------------------------
    // Ranges
    // ------------------------------------------------------------------

    /// Interval that provably contains the value of `e`.
    fn rng(&self, e: &Expr, env: &Env) -> Option<(i128, i128)> {
        let ty = e.ty();
        let tr = ty_range(ty);
        let fits = |r: (i128, i128)| tr.is_some_and(|(lo, hi)| r.0 >= lo && r.1 <= hi);
        match e {
            Expr::Const { .. } => const_i128(e).map(|v| (v, v)).or(tr),
            Expr::Local { name, .. } => env.ranges.get(name).copied().or(tr),
            Expr::Resize { arg, .. } | Expr::Cast { arg, .. } => match self.rng(arg, env) {
                Some(r) if fits(r) => Some(r),
                _ => tr,
            },
            Expr::Binary {
                op: op @ (BinOp::Add | BinOp::Sub | BinOp::Mul),
                lhs,
                rhs,
                ..
            } => match self.raw_arith_range(*op, lhs, rhs, env) {
                Some(r) if fits(r) => Some(r),
                _ => tr,
            },
            _ => tr,
        }
    }

    /// Interval of `lhs op rhs` before truncation to the node type.
    fn raw_arith_range(
        &self,
        op: BinOp,
        lhs: &Expr,
        rhs: &Expr,
        env: &Env,
    ) -> Option<(i128, i128)> {
        let (a, b) = (self.rng(lhs, env)?, self.rng(rhs, env)?);
        let lim = 1i128 << 100;
        if [a.0, a.1, b.0, b.1].iter().any(|v| v.abs() > lim) {
            return None;
        }
        Some(match op {
            BinOp::Add => (a.0 + b.0, a.1 + b.1),
            BinOp::Sub => (a.0 - b.1, a.1 - b.0),
            _ => {
                if [a.0, a.1, b.0, b.1].iter().any(|v| v.abs() > (1i128 << 50)) {
                    return None;
                }
                let c = [a.0 * b.0, a.0 * b.1, a.1 * b.0, a.1 * b.1];
                (*c.iter().min()?, *c.iter().max()?)
            }
        })
    }

