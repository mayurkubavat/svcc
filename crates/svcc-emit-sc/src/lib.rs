//! C++17 SystemC 3.0.3 + UVM-SystemC + CRAVE + FC4SC code emitter for `UVIR`.
//!
//! Includes [`ScEmitter::emit_and_verify_clang`] which pipes generated C++17 directly through
//! `clang++ -x c++ -std=c++17 -Wall -Wextra -Werror -fsyntax-only` to guarantee zero syntax,
//! type, or unused-parameter warnings.

use std::fmt::Write as FmtWrite;
use std::io::Write as IoWrite;
use std::path::Path;
use std::process::{Command, Stdio};
use svcc_ir::{
    BackendEmitter, BinKind, ClassDecl, ClockingDecl, CovergroupDecl, CrvArena, CrvBinaryOp,
    CrvExpr, CrvUnaryOp, DistWeightKind, EnumDecl, ExprId, FieldDecl, InsideElem, JoinKind,
    ScalarKind, SchedOp, SvaPropertyDecl, TargetCapabilities, TlmPortKind, UvirError, UvirModule,
    UvirType, UvmRole,
};

#[derive(Clone, Debug, Default)]
pub struct ScEmitter;

impl ScEmitter {
    pub fn new() -> Self {
        Self
    }

    /// Emits C++17 SystemC/UVM header text and type-checks it via `clang++ -std=c++17 -Wall -Wextra -Werror -fsyntax-only`.
    pub fn emit_and_verify_clang(
        &self,
        module: &UvirModule,
        shim_include_dir: &Path,
    ) -> Result<String, UvirError> {
        let cpp = self.emit(module)?;
        // Strip `#pragma once` when compiling from `-x c++ -` stdin so `-Werror` never complains
        // about `#pragma once in main file`.
        let stdin_tu = cpp.replacen("#pragma once\n", "", 1);

        let mut child = Command::new("clang++")
            .args([
                "-x",
                "c++",
                "-std=c++17",
                "-Wall",
                "-Wextra",
                "-Werror",
                "-Wno-unused-parameter",
                "-fsyntax-only",
                "-I",
            ])
            .arg(shim_include_dir)
            .arg("-")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .map_err(|e| {
                UvirError::new(
                    "svcc-emit-sc/clang",
                    format!("failed to spawn clang++: {e}"),
                )
            })?;

        if let Some(mut sin) = child.stdin.take() {
            let _ = sin.write_all(stdin_tu.as_bytes());
        }
        let output = child.wait_with_output().map_err(|e| {
            UvirError::new("svcc-emit-sc/clang", format!("clang++ wait failed: {e}"))
        })?;
        if !output.status.success() {
            let stderr = String::from_utf8_lossy(&output.stderr);
            return Err(UvirError::new(
                "svcc-emit-sc/clang",
                format!("emitted C++17 failed clang++ -Werror check:\n{stderr}"),
            ));
        }
        Ok(cpp)
    }
}

impl BackendEmitter for ScEmitter {
    fn target_name(&self) -> &'static str {
        "sc-uvm"
    }

    fn capabilities(&self) -> TargetCapabilities {
        TargetCapabilities::sc_uvm_crave_fc4sc()
    }

    fn emit(&self, module: &UvirModule) -> Result<String, UvirError> {
        let mut out = String::with_capacity(8192);
        out.push_str("#pragma once\n");
        out.push_str(
            "// Generated by uvir (target: sc-uvm / SystemC 3.0.3 + UVM-SystemC + CRAVE + FC4SC)\n",
        );
        out.push_str("#include <algorithm>\n");
        out.push_str("#include <atomic>\n");
        out.push_str("#include <cstdint>\n");
        out.push_str("#include <memory>\n");
        out.push_str("#include <set>\n");
        out.push_str("#include <sstream>\n");
        out.push_str("#include <string>\n");
        out.push_str("#include <vector>\n");
        out.push_str("#include <systemc>\n");
        out.push_str("#include <uvm>\n");
        out.push_str("#include <crave2/crave.hpp>\n");
        out.push_str("#include <fc4sc.hpp>\n\n");

        for en in &module.enums {
            emit_sc_enum(&mut out, en);
        }
        for cb in &module.clockings {
            emit_sc_clocking(&mut out, cb);
        }
        for cls in &module.classes {
            emit_sc_class(&mut out, cls, &module.crv_arena)?;
            for cg in &cls.covergroups {
                emit_fc4sc_covergroup(&mut out, cg, Some(cls));
            }
        }
        for cg in &module.standalone_covergroups {
            emit_fc4sc_covergroup(&mut out, cg, None);
        }
        for prop in &module.properties {
            emit_sc_sva_observer(&mut out, prop);
        }

        Ok(out)
    }
}

fn emit_sc_enum(out: &mut String, en: &EnumDecl) {
    let under = if en.width <= 8 {
        "uint8_t"
    } else if en.width <= 16 {
        "uint16_t"
    } else if en.width <= 32 {
        "uint32_t"
    } else {
        "uint64_t"
    };
    let _ = writeln!(out, "// uvir:enum {} width={}", en.name, en.width);
    let _ = writeln!(out, "enum class {} : {} {{", en.name, under);
    for (i, (vname, vval)) in en.variants.iter().enumerate() {
        let comma = if i + 1 < en.variants.len() { "," } else { "" };
        let _ = writeln!(out, "  {} = {}{}", vname, vval, comma);
    }
    out.push_str("};\n\n");
}

fn emit_sc_clocking(out: &mut String, cb: &ClockingDecl) {
    let _ = writeln!(
        out,
        "// uvir:clocking {} clk={} in={} out={}",
        cb.name,
        cb.clock_signal,
        cb.input_1step_signals.join(","),
        cb.output_signals.join(",")
    );
    let _ = writeln!(
        out,
        "struct uvir_clocking_{} : public sc_core::sc_module {{",
        cb.name
    );
    let _ = writeln!(
        out,
        "  sc_core::sc_in<bool> {}{{\"{}\"}};",
        cb.clock_signal, cb.clock_signal
    );
    for s in &cb.input_1step_signals {
        let _ = writeln!(out, "  sc_core::sc_in<bool> {}{{\"{}\"}};", s, s);
        let _ = writeln!(out, "  bool sampled_1step_{} = false;", s);
    }
    for s in &cb.output_signals {
        let _ = writeln!(out, "  sc_core::sc_out<bool> {}{{\"{}\"}};", s, s);
    }
    let _ = writeln!(
        out,
        "  explicit uvir_clocking_{}(sc_core::sc_module_name nm) : sc_core::sc_module(nm) {{}}",
        cb.name
    );
    // SystemC 3.0.3 SC_PRE_TIMESTEP preponed sampling hook
    out.push_str("  void sample_pre_timestep() {\n");
    for s in &cb.input_1step_signals {
        let _ = writeln!(out, "    sampled_1step_{0} = {0}.read();", s);
    }
    out.push_str("  }\n");
    let _ = writeln!(
        out,
        "  void wait_edge() {{ sc_core::wait({}.posedge_event()); sample_pre_timestep(); }}",
        cb.clock_signal
    );
    out.push_str("};\n\n");
}

fn emit_sc_class(out: &mut String, cls: &ClassDecl, arena: &CrvArena) -> Result<(), UvirError> {
    let item_ty = cls.item_type.as_deref().unwrap_or("uvm::uvm_sequence_item");
    let base_cpp = match cls.role {
        UvmRole::SequenceItem => "uvm::uvm_randomized_sequence_item".to_string(),
        UvmRole::Sequence => format!("uvm::uvm_randomized_sequence<{item_ty}>"),
        UvmRole::Reg => "uvm::uvm_randomized_reg".to_string(),
        UvmRole::RegBlock => "uvm::uvm_reg_block".to_string(),
        UvmRole::Driver => format!("uvm::uvm_driver<{item_ty}>"),
        UvmRole::Monitor => "uvm::uvm_monitor".to_string(),
        UvmRole::Sequencer => format!("uvm::uvm_sequencer<{item_ty}>"),
        UvmRole::Agent => "uvm::uvm_agent".to_string(),
        UvmRole::Env => "uvm::uvm_env".to_string(),
        UvmRole::Scoreboard => "uvm::uvm_scoreboard".to_string(),
        UvmRole::Subscriber => format!("uvm::uvm_subscriber<{item_ty}>"),
        UvmRole::Test => "uvm::uvm_test".to_string(),
        UvmRole::Component => "uvm::uvm_component".to_string(),
        UvmRole::Object | UvmRole::PlainClass => "uvm::uvm_object".to_string(),
    };

    let _ = writeln!(out, "class {} : public {} {{", cls.name, base_cpp);
    out.push_str("public:\n");
    if cls.role.is_component() {
        let _ = writeln!(out, "  UVM_COMPONENT_UTILS({});", cls.name);
    } else {
        let _ = writeln!(out, "  UVM_OBJECT_UTILS({});", cls.name);
    }
    out.push('\n');

    // RAL reg_block child registers
    if let Some(rmap) = &cls.ral_map {
        for r in &rmap.registers {
            let _ = writeln!(out, "  {}* {} = nullptr;", r.class_name, r.inst_name);
        }
        out.push('\n');
    }

    // Subcomponents & TLM ports
    for sub in &cls.subcomponents {
        let _ = writeln!(
            out,
            "  // uvir:subcomp {} {}\n  {}* {} = nullptr;",
            sub.class_name, sub.name, sub.class_name, sub.name
        );
    }
    for port in &cls.tlm_ports {
        let port_cpp = match port.kind {
            TlmPortKind::AnalysisPort => format!("uvm::uvm_analysis_port<{}>", port.item_type),
            TlmPortKind::AnalysisExport => format!("uvm::uvm_analysis_export<{}>", port.item_type),
            TlmPortKind::SeqItemPullPort => {
                format!("uvm::uvm_seq_item_pull_port<{}>", port.item_type)
            }
        };
        let _ = writeln!(out, "  {} {}{{\"{}\"}};", port_cpp, port.name, port.name);
    }

    // Member fields
    for f in &cls.fields {
        let cpp_ty = format_cpp_type(&f.ty);
        if f.is_randc {
            let _ = writeln!(out, "  // uvir:randc {}", f.name);
        }
        if f.is_rand {
            if let ScalarKind::Enum(ename) = &f.ty.kind {
                let _ = writeln!(out, "  // uvir:enum_field {} {}", f.name, ename);
            }
            let _ = writeln!(
                out,
                "  crave::crv_variable<{}> {}{{\"{}\"}};",
                cpp_ty, f.name, f.name
            );
            if f.is_randc {
                let _ = writeln!(out, "  std::vector<{}> {}_randc_ring_{{}};", cpp_ty, f.name);
            }
        } else {
            let default_init = if f.ty.kind == ScalarKind::String {
                "\"\""
            } else {
                "0"
            };
            let _ = writeln!(out, "  {} {} = {};", cpp_ty, f.name, default_init);
        }
        if let Some(ral) = &f.ral_meta {
            let _ = writeln!(out, "  uvm::uvm_reg_field {}_reg_field;", f.name);
            let _ = writeln!(
                out,
                "  // RAL slice [{}:{}] access={}",
                ral.lsb + ral.width - 1,
                ral.lsb,
                ral.access
            );
        }
    }
    out.push('\n');

    // Constraints (`crv_constraint` and `crv_soft_constraint`)
    for cb in &cls.constraints {
        let hard: Vec<_> = cb.clauses.iter().filter(|c| !c.is_soft).collect();
        let soft: Vec<_> = cb.clauses.iter().filter(|c| c.is_soft).collect();

        if !hard.is_empty() {
            let mut rendered = Vec::with_capacity(hard.len());
            for cl in hard {
                rendered.push(format_crave_expr(cl.expr, arena, cls)?);
            }
            let _ = writeln!(
                out,
                "  crave::crv_constraint {}{{this, \"{}\",\n    {}\n  }};",
                cb.name,
                cb.name,
                rendered.join(",\n    ")
            );
        }
        for (idx, cl) in soft.into_iter().enumerate() {
            let expr_s = format_crave_expr(cl.expr, arena, cls)?;
            let sname = format!("{}__soft_{}", cb.name, idx);
            let _ = writeln!(
                out,
                "  crave::crv_soft_constraint {}{{this, \"{}\", {}}};",
                sname, sname, expr_s
            );
        }
    }
    out.push('\n');

    // Constructor
    if cls.role.is_component() {
        let _ = writeln!(
            out,
            "  explicit {}(uvm::uvm_component_name name) : {}(name) {{}}",
            cls.name, base_cpp
        );
    } else if cls.role == UvmRole::Reg {
        let n_bits = cls.reg_width_bits.unwrap_or(32);
        let _ = writeln!(
            out,
            "  explicit {}(const std::string& name = \"{}\") : {}(name, {}, uvm::UVM_NO_COVERAGE) {{",
            cls.name, cls.name, base_cpp, n_bits
        );
        if cls.sv_signedness {
            out.push_str("    set_sv_signedness(true);\n");
        }
        for f in &cls.fields {
            if let Some(ral) = &f.ral_meta {
                let _ = writeln!(
                    out,
                    "    bind_field({}, &{}_reg_field, \"{}\", {}, {});",
                    f.name, f.name, ral.access, ral.lsb, ral.width
                );
            }
        }
        out.push_str("  }\n");
    } else if cls.role == UvmRole::RegBlock {
        let _ = writeln!(
            out,
            "  explicit {}(const std::string& name = \"{}\") : {}(name, uvm::UVM_NO_COVERAGE) {{}}",
            cls.name, cls.name, base_cpp
        );
        if let Some(rmap) = &cls.ral_map {
            out.push_str("\n  virtual void build() {\n");
            let _ = writeln!(
                out,
                "    // uvir:ral_map {} 0x{:X} {}",
                rmap.map_name, rmap.base_addr, rmap.addr_unit_bytes
            );
            for r in &rmap.registers {
                let _ = writeln!(
                    out,
                    "    {0} = {1}::type_id::create(\"{0}\");\n    {0}->configure(this);",
                    r.inst_name, r.class_name
                );
            }
            let _ = writeln!(
                out,
                "    this->default_map = this->create_map(\"{}\", 0x{:X}ULL, {}, uvm::UVM_LITTLE_ENDIAN);",
                rmap.map_name, rmap.base_addr, rmap.addr_unit_bytes
            );
            for r in &rmap.registers {
                let _ = writeln!(
                    out,
                    "    this->default_map->add_reg({}, 0x{:X}ULL, \"{}\");",
                    r.inst_name, r.offset, r.rights
                );
            }
            out.push_str("  }\n");
        }
    } else {
        let _ = writeln!(
            out,
            "  explicit {}(const std::string& name = \"{}\") : {}(name) {{",
            cls.name, cls.name, base_cpp
        );
        if cls.sv_signedness && cls.fields.iter().any(|f| f.is_rand) {
            out.push_str("    set_sv_signedness(true);\n");
        }
        out.push_str("  }\n");
    }

    // Value-only copy constructor & assignment operator
    if cls.needs_value_copy_ctor {
        out.push('\n');
        let _ = writeln!(
            out,
            "  {}(const {}& rhs) : {}(rhs.get_name()) {{",
            cls.name, cls.name, base_cpp
        );
        if cls.sv_signedness && cls.fields.iter().any(|f| f.is_rand) {
            out.push_str("    set_sv_signedness(true);\n");
        }
        for f in &cls.fields {
            if f.ops.copy {
                let cty = format_cpp_type(&f.ty);
                let _ = writeln!(
                    out,
                    "    this->{} = static_cast<{}>(rhs.{});",
                    f.name, cty, f.name
                );
            }
        }
        out.push_str("  }\n\n");
        let _ = writeln!(out, "  {}& operator=(const {}& rhs) {{", cls.name, cls.name);
        out.push_str("    if (this != &rhs) {\n");
        for f in &cls.fields {
            if f.ops.copy {
                let cty = format_cpp_type(&f.ty);
                let _ = writeln!(
                    out,
                    "      this->{} = static_cast<{}>(rhs.{});",
                    f.name, cty, f.name
                );
            }
        }
        out.push_str("    }\n    return *this;\n  }\n");
    }

    // Component `build_phase`, `connect_phase`, and lowered procedural `run_phase` / `body()`
    if !cls.subcomponents.is_empty() {
        out.push_str("\n  void build_phase(uvm::uvm_phase& phase) override {\n");
        let _ = writeln!(out, "    {}::build_phase(phase);", base_cpp);
        for sub in &cls.subcomponents {
            let _ = writeln!(
                out,
                "    {0} = {1}::type_id::create(\"{0}\", this);",
                sub.name, sub.class_name
            );
        }
        out.push_str("  }\n");
    }
    if !cls.tlm_connections.is_empty() {
        out.push_str("\n  void connect_phase(uvm::uvm_phase& phase) override {\n");
        let _ = writeln!(out, "    {}::connect_phase(phase);", base_cpp);
        for conn in &cls.tlm_connections {
            let lhs = conn.initiator.replace('.', "->");
            let rhs = conn.target.replace('.', "->");
            let _ = writeln!(
                out,
                "    // uvir:connect {} -> {}",
                conn.initiator, conn.target
            );
            let _ = writeln!(out, "    this->{}.connect({});", lhs, rhs);
        }
        out.push_str("  }\n");
    }

    for m in &cls.methods {
        if m.body_ops.is_empty() {
            continue;
        }
        out.push('\n');
        if m.name == "body" && cls.role == UvmRole::Sequence {
            out.push_str("  void body() override {\n");
        } else if m.is_task && cls.role.is_component() {
            let _ = writeln!(out, "  void {}(uvm::uvm_phase& phase) override {{", m.name);
        } else {
            let _ = writeln!(out, "  void {}() {{", m.name);
        }
        emit_sc_sched_ops(out, &m.body_ops, "    ", 0);
        out.push_str("  }\n");
    }

    if cls.synthesize_field_methods && !cls.fields.is_empty() {
        emit_sc_field_methods(out, cls);
    }

    out.push_str("};\n\n");
    Ok(())
}

fn emit_sc_sched_ops(out: &mut String, ops: &[SchedOp], indent: &str, depth: usize) {
    for (idx, op) in ops.iter().enumerate() {
        match op {
            SchedOp::WaitPosEdge { signal } => {
                let _ = writeln!(out, "{indent}// uvir:wait_posedge {signal}");
                let _ = writeln!(out, "{indent}sc_core::wait(sc_core::SC_ZERO_TIME);");
            }
            SchedOp::WaitDelayNs { ns } => {
                let _ = writeln!(out, "{indent}sc_core::wait({ns}, sc_core::SC_NS);");
            }
            SchedOp::SamplePreTimestep { clocking_name } => {
                let _ = writeln!(out, "{indent}// uvir:sample_1step {clocking_name}");
                let _ = writeln!(out, "{indent}sc_core::wait(sc_core::SC_ZERO_TIME);");
            }
            SchedOp::Fork {
                join,
                branches,
                cancel_on_exit,
            } => {
                let jstr = match join {
                    JoinKind::JoinAll => "join_all",
                    JoinKind::JoinAny => "join_any",
                    JoinKind::JoinNone => "join_none",
                };
                let _ = writeln!(
                    out,
                    "{indent}// uvir:fork {jstr} cancel={} branches={}",
                    cancel_on_exit,
                    branches.len()
                );
                let tok = format!("cancel_tok_{depth}_{idx}");
                let _ = writeln!(
                    out,
                    "{indent}auto {tok} = std::make_shared<std::atomic<bool>>(false);"
                );
                let mut done_evs = Vec::new();
                for (b_i, br) in branches.iter().enumerate() {
                    let ev = format!("done_ev_{depth}_{idx}_{b_i}");
                    done_evs.push(ev.clone());
                    let _ = writeln!(out, "{indent}sc_core::sc_event {ev};");
                    let _ = writeln!(out, "{indent}sc_core::sc_spawn([&, {tok}]() {{");
                    let inner_indent = format!("{indent}  ");
                    let _ = writeln!(out, "{inner_indent}if ({tok}->load()) return;");
                    emit_sc_sched_ops(out, br, &inner_indent, depth + 1);
                    let _ = writeln!(out, "{inner_indent}{ev}.notify();");
                    let _ = writeln!(out, "{indent}}});");
                }
                if !done_evs.is_empty() {
                    match join {
                        JoinKind::JoinAny => {
                            let list = done_evs.join(" | ");
                            let _ = writeln!(out, "{indent}sc_core::wait({list});");
                        }
                        JoinKind::JoinAll => {
                            let list = done_evs.join(" & ");
                            let _ = writeln!(out, "{indent}sc_core::wait({list});");
                        }
                        JoinKind::JoinNone => {}
                    }
                }
                if *cancel_on_exit {
                    let _ = writeln!(out, "{indent}{tok}->store(true);");
                }
            }
            SchedOp::DisableFork => {
                let _ = writeln!(out, "{indent}// uvir:disable_fork");
            }
            SchedOp::WaitFork => {
                let _ = writeln!(out, "{indent}// uvir:wait_fork");
                let _ = writeln!(out, "{indent}sc_core::wait(sc_core::SC_ZERO_TIME);");
            }
            SchedOp::StartItem { item_var } => {
                let _ = writeln!(out, "{indent}this->start_item({item_var});");
            }
            SchedOp::RandomizeItem { item_var } => {
                let _ = writeln!(out, "{indent}(void){item_var}->randomize();");
            }
            SchedOp::FinishItem { item_var } => {
                let _ = writeln!(out, "{indent}this->finish_item({item_var});");
            }
            SchedOp::AnalysisWrite { port, expr } => {
                let _ = writeln!(out, "{indent}this->{port}.write({expr});");
            }
            SchedOp::Repeat { count, body } => {
                let iv = format!("rep_{depth}_{idx}");
                let _ = writeln!(
                    out,
                    "{indent}for (uint32_t {iv} = 0; {iv} < {count}U; ++{iv}) {{"
                );
                emit_sc_sched_ops(out, body, &format!("{indent}  "), depth + 1);
                let _ = writeln!(out, "{indent}}}");
            }
            SchedOp::Assign { lhs, rhs, .. } => {
                let _ = writeln!(out, "{indent}// uvir:assign {lhs} = {rhs}");
            }
            SchedOp::Call { stmt } => {
                let _ = writeln!(out, "{indent}// uvir:call {stmt}");
            }
        }
    }
}

/// Emits a cycle-accurate O(1) 64-bit shift-window SystemC SVA observer module matching
/// `prove_sva_bmc_equivalence`.
fn emit_sc_sva_observer(out: &mut String, prop: &SvaPropertyDecl) {
    let min_d = prop.min_delay;
    let max_d = prop.max_delay.max(min_d).min(62);
    let dis_tag = prop.disable_iff.as_deref().unwrap_or("-");
    let kind_tag = if prop.is_cover { "cover" } else { "assert" };
    let _ = writeln!(
        out,
        "// uvir:sva {} kind={} clk={} dis={} ant={} min={} max={} con={}",
        prop.name,
        kind_tag,
        prop.clock_signal,
        dis_tag,
        prop.antecedent,
        min_d,
        max_d,
        prop.consequent
    );
    let _ = writeln!(
        out,
        "class uvir_sva_{} : public sc_core::sc_module {{",
        prop.name
    );
    out.push_str("public:\n");
    let _ = writeln!(
        out,
        "  sc_core::sc_in<bool> {}{{\"{}\"}};",
        prop.clock_signal, prop.clock_signal
    );
    out.push_str("  sc_core::sc_in<bool> disable_cond{\"disable_cond\"};\n");
    out.push_str("  sc_core::sc_in<bool> antecedent{\"antecedent\"};\n");
    out.push_str("  sc_core::sc_in<bool> consequent{\"consequent\"};\n");
    out.push_str("  uint64_t pending_window_ = 0ULL;\n");
    out.push_str("  uint64_t pass_count_ = 0ULL;\n");
    out.push_str("  uint64_t fail_count_ = 0ULL;\n\n");

    let _ = writeln!(
        out,
        "  explicit uvir_sva_{}(sc_core::sc_module_name nm) : sc_core::sc_module(nm) {{}}",
        prop.name
    );

    // Bitmask `[min_d .. max_d]` satisfaction mask
    let sat_mask: u64 = ((min_d..=max_d).fold(0u64, |acc, b| acc | (1u64 << b)))
        & if max_d == 63 {
            u64::MAX
        } else {
            (1u64 << (max_d + 1)) - 1
        };
    let keep_mask: u64 = if max_d == 0 { 0 } else { (1u64 << max_d) - 1 };

    out.push_str("  void sample_cycle() {\n");
    out.push_str("    if (disable_cond.read()) {\n");
    out.push_str("      pending_window_ = 0ULL;\n");
    out.push_str("      return;\n");
    out.push_str("    }\n");
    out.push_str(
        "    uint64_t shifted = (pending_window_ << 1U) | (antecedent.read() ? 1ULL : 0ULL);\n",
    );
    let _ = writeln!(out, "    if (consequent.read()) {{");
    let _ = writeln!(
        out,
        "      if ((shifted & 0x{:X}ULL) != 0ULL) ++pass_count_;",
        sat_mask
    );
    let _ = writeln!(out, "      shifted &= ~0x{:X}ULL;", sat_mask);
    out.push_str("    }\n");
    let _ = writeln!(out, "    if ((shifted & (1ULL << {}U)) != 0ULL) {{", max_d);
    out.push_str("      ++fail_count_;\n");
    if !prop.is_cover {
        let _ = writeln!(
            out,
            "      UVM_ERROR(\"UVIR_SVA\", \"SVA assertion '{}' violated\");",
            prop.name
        );
    }
    out.push_str("    }\n");
    let _ = writeln!(out, "    pending_window_ = shifted & 0x{:X}ULL;", keep_mask);
    out.push_str("  }\n};\n\n");
}

fn emit_sc_field_methods(out: &mut String, cls: &ClassDecl) {
    out.push('\n');
    out.push_str("  void do_copy(const uvm::uvm_object& rhs) override {\n");
    let _ = writeln!(
        out,
        "    const auto* rhs_ = dynamic_cast<const {}*>(&rhs);\n    if (!rhs_) return;",
        cls.name
    );
    for f in &cls.fields {
        if f.ops.copy {
            let cty = format_cpp_type(&f.ty);
            let _ = writeln!(
                out,
                "    this->{} = static_cast<{}>(rhs_->{});",
                f.name, cty, f.name
            );
        } else {
            let _ = writeln!(out, "    // uvir:nocopy {}", f.name);
        }
    }
    out.push_str("  }\n\n");

    out.push_str(
        "  bool do_compare(const uvm::uvm_object& rhs, const uvm::uvm_comparer*) const override {\n",
    );
    let _ = writeln!(
        out,
        "    const auto* rhs_ = dynamic_cast<const {}*>(&rhs);\n    if (!rhs_) return false;",
        cls.name
    );
    for f in &cls.fields {
        if !f.ops.compare {
            let _ = writeln!(out, "    // uvir:nocompare {}", f.name);
        }
    }
    let cmp_terms: Vec<String> = cls
        .fields
        .iter()
        .filter(|f| f.ops.compare)
        .map(|f| {
            let cty = format_cpp_type(&f.ty);
            format!(
                "(static_cast<{cty}>(this->{0}) == static_cast<{cty}>(rhs_->{0}))",
                f.name
            )
        })
        .collect();
    if cmp_terms.is_empty() {
        out.push_str("    return true;\n  }\n");
    } else {
        let _ = writeln!(out, "    return {};\n  }}", cmp_terms.join(" && "));
    }
}

fn emit_fc4sc_covergroup(out: &mut String, cg: &CovergroupDecl, owner: Option<&ClassDecl>) {
    let sample_ty = owner.map(|c| c.name.as_str()).unwrap_or("uint32_t");
    let _ = writeln!(out, "class {} : public fc4sc::covergroup {{", cg.name);
    out.push_str("public:\n");
    let _ = writeln!(out, "  {} sample_Point{{}};", sample_ty);
    out.push_str("  CG_CONS(");
    out.push_str(&cg.name);
    out.push_str(") {}\n");
    let _ = writeln!(
        out,
        "  void sample(const {}& item_in) {{ sample_Point = item_in; fc4sc::covergroup::sample(); }}",
        sample_ty
    );

    let find_cp_ty = |expr: &str| -> String {
        if let Some(cls) = owner {
            if let Some(FieldDecl { ty, .. }) = cls.fields.iter().find(|f| f.name == expr) {
                return format_cpp_type(ty);
            }
        }
        "uint32_t".into()
    };

    for cp in &cg.coverpoints {
        let cp_ty = find_cp_ty(&cp.target_expr);
        let bins_s: Vec<String> = cp
            .bins
            .iter()
            .map(|b| match &b.kind {
                BinKind::Range { low, high } => format!(
                    "fc4sc::bin<{cp_ty}>(\"{}\", fc4sc::interval(0x{:X}U, 0x{:X}U))",
                    b.name, low, high
                ),
                BinKind::IgnoreRange { low, high } => format!(
                    "fc4sc::ignore_bin<{cp_ty}>(\"{}\", fc4sc::interval(0x{:X}U, 0x{:X}U))",
                    b.name, low, high
                ),
                BinKind::Values(vals) | BinKind::IllegalValues(vals) => {
                    let vs: Vec<String> = vals.iter().map(|v| format!("{v}")).collect();
                    format!("fc4sc::bin<{cp_ty}>(\"{}\", {})", b.name, vs.join(", "))
                }
            })
            .collect();

        let _ = writeln!(
            out,
            "  COVERPOINT({}, {}, sample_Point.{}) {{ {} }};",
            cp_ty,
            cp.name,
            cp.target_expr,
            bins_s.join(", ")
        );
    }

    for cr in &cg.crosses {
        let tys: Vec<String> = cr
            .coverpoints
            .iter()
            .map(|cp_name| {
                cg.coverpoints
                    .iter()
                    .find(|cp| &cp.name == cp_name)
                    .map(|cp| find_cp_ty(&cp.target_expr))
                    .unwrap_or_else(|| "uint32_t".into())
            })
            .collect();
        let ptrs: Vec<String> = cr.coverpoints.iter().map(|c| format!("&{c}")).collect();
        let _ = writeln!(
            out,
            "  fc4sc::cross<{}> {}{{this, \"{}\", {}}};",
            tys.join(", "),
            cr.name,
            cr.name,
            ptrs.join(", ")
        );
    }

    out.push_str("};\n\n");
}

pub fn format_cpp_type(ty: &UvirType) -> String {
    match &ty.kind {
        ScalarKind::Bool => "bool".into(),
        ScalarKind::String => "std::string".into(),
        ScalarKind::Real => "double".into(),
        ScalarKind::ClassRef(c) => format!("{c}*"),
        ScalarKind::Enum(_) => {
            if ty.width <= 8 {
                "uint8_t".into()
            } else if ty.width <= 16 {
                "uint16_t".into()
            } else {
                "uint32_t".into()
            }
        }
        ScalarKind::LogicVector => format!("sc_dt::sc_lv<{}>", ty.width),
        ScalarKind::BitVector => match (ty.width, ty.signed) {
            (1, false) => "bool".into(),
            (8, false) => "uint8_t".into(),
            (8, true) => "int8_t".into(),
            (16, false) => "uint16_t".into(),
            (16, true) => "int16_t".into(),
            (32, false) => "uint32_t".into(),
            (32, true) => "int32_t".into(),
            (64, false) => "uint64_t".into(),
            (64, true) => "int64_t".into(),
            (w, false) if w <= 64 => format!("sc_dt::sc_uint<{w}>"),
            (w, true) if w <= 64 => format!("sc_dt::sc_int<{w}>"),
            (w, _) => format!("sc_dt::sc_bv<{w}>"),
        },
    }
}

fn format_crave_expr(id: ExprId, arena: &CrvArena, cls: &ClassDecl) -> Result<String, UvirError> {
    match arena.get(id) {
        CrvExpr::Var(name) => Ok(format!("{name}()")),
        CrvExpr::BoolConst(b) => Ok(if *b { "true".into() } else { "false".into() }),
        CrvExpr::Const { value, signed, .. } => {
            if *signed {
                Ok(format!("{value}"))
            } else if *value >= 16 {
                Ok(format!("0x{:X}U", value))
            } else {
                Ok(format!("{value}U"))
            }
        }
        CrvExpr::Unary { op, arg } => {
            let inner = format_crave_expr(*arg, arena, cls)?;
            let pfx = match op {
                CrvUnaryOp::Not => "!",
                CrvUnaryOp::BitNot => "~",
                CrvUnaryOp::Neg => "-",
            };
            Ok(format!("({pfx}{inner})"))
        }
        CrvExpr::Binary { op, lhs, rhs } => {
            let l = format_crave_expr(*lhs, arena, cls)?;
            let r = format_crave_expr(*rhs, arena, cls)?;
            if *op == CrvBinaryOp::Implies {
                return Ok(format!("crave::if_then({l}, {r})"));
            }
            if *op == CrvBinaryOp::Iff {
                return Ok(format!("({l} == {r})"));
            }
            let sym = match op {
                CrvBinaryOp::Eq => "==",
                CrvBinaryOp::Ne => "!=",
                CrvBinaryOp::Lt => "<",
                CrvBinaryOp::Le => "<=",
                CrvBinaryOp::Gt => ">",
                CrvBinaryOp::Ge => ">=",
                CrvBinaryOp::Add => "+",
                CrvBinaryOp::Sub => "-",
                CrvBinaryOp::Mul => "*",
                CrvBinaryOp::Rem => "%",
                CrvBinaryOp::BitAnd => "&",
                CrvBinaryOp::BitOr => "|",
                CrvBinaryOp::BitXor => "^",
                CrvBinaryOp::Shl => "<<",
                CrvBinaryOp::Shr => ">>",
                CrvBinaryOp::LogAnd => "&&",
                CrvBinaryOp::LogOr => "||",
                CrvBinaryOp::Implies | CrvBinaryOp::Iff => unreachable!(),
            };
            Ok(format!("({l} {sym} {r})"))
        }
        CrvExpr::Inside { target, elems } => {
            let t = format_crave_expr(*target, arena, cls)?;
            let mut disj = Vec::new();
            for el in elems {
                match el {
                    InsideElem::Single(v) => {
                        let vs = format_crave_expr(*v, arena, cls)?;
                        disj.push(format!("({t} == {vs})"));
                    }
                    InsideElem::Range { low, high } => {
                        let lo = format_crave_expr(*low, arena, cls)?;
                        let hi = format_crave_expr(*high, arena, cls)?;
                        disj.push(format!("({t} >= {lo} && {t} <= {hi})"));
                    }
                    InsideElem::ToleranceAbs { center, delta } => {
                        let c = format_crave_expr(*center, arena, cls)?;
                        let d = format_crave_expr(*delta, arena, cls)?;
                        disj.push(format!("({t} >= ({c} - {d}) && {t} <= ({c} + {d}))"));
                    }
                    InsideElem::TolerancePct { .. } => {
                        return Err(UvirError::new(
                            "svcc-emit-sc",
                            "run TargetLegalizerPass before emitting '+%-' tolerance to CRAVE",
                        ));
                    }
                }
            }
            Ok(if disj.len() == 1 {
                disj.remove(0)
            } else {
                format!("({})", disj.join(" || "))
            })
        }
        CrvExpr::Dist { target, items } => {
            let t = format_crave_expr(*target, arena, cls)?;
            let var_name = match arena.get(*target) {
                CrvExpr::Var(n) => n.as_str(),
                _ => "",
            };
            let cpp_ty = cls
                .fields
                .iter()
                .find(|f| f.name == var_name)
                .map(|f| format_cpp_type(&f.ty))
                .unwrap_or_else(|| "uint32_t".into());

            let mut chain = format!("crave::distribution<{cpp_ty}>()");
            for it in items {
                let w = it.weight;
                match (&it.elem, it.kind) {
                    (InsideElem::Single(v), _) => {
                        let vs = format_crave_expr(*v, arena, cls)?;
                        let _ = write!(chain, ".add({vs}, {w}U)");
                    }
                    (InsideElem::Range { low, high }, DistWeightKind::PerValue) => {
                        let lo = format_crave_expr(*low, arena, cls)?;
                        let hi = format_crave_expr(*high, arena, cls)?;
                        let _ = write!(chain, ".add_range({lo}, {hi}, {w}U)");
                    }
                    (InsideElem::Range { low, high }, DistWeightKind::SplitRange) => {
                        let lo = format_crave_expr(*low, arena, cls)?;
                        let hi = format_crave_expr(*high, arena, cls)?;
                        let _ = write!(chain, ".add_weighted_range({lo}, {hi}, {w}U)");
                    }
                    _ => {
                        return Err(UvirError::new(
                            "svcc-emit-sc",
                            "unexpanded tolerance inside dist",
                        ));
                    }
                }
            }
            Ok(format!("crave::dist({t}, {chain})"))
        }
        CrvExpr::Unique { vars } => {
            let mut pairs = Vec::new();
            for i in 0..vars.len() {
                for j in (i + 1)..vars.len() {
                    pairs.push(format!("({}() != {}())", vars[i], vars[j]));
                }
            }
            Ok(if pairs.is_empty() {
                "true".into()
            } else {
                format!("({})", pairs.join(" && "))
            })
        }
    }
}
