//! IEEE 1800-2023 SystemVerilog & IEEE 1800.2-2020 UVM backend emitter for `UVIR`.
//!
//! Emits lint-clean UVM-SV classes (avoiding deprecated `` `uvm_field_* `` macro bloat in favor
//! of explicit `do_copy` / `do_compare` / `convert2string` methods, while also preserving
//! field compare/copy masks) and provides [`SvEmitter::emit_and_verify`] to parse-check every
//! emitted SystemVerilog buffer through the pinned [`svlang`] front-end.

use std::fmt::Write;
use svlang::{Compilation, DiagnosticStage, Severity};
use uvir_ir::{
    BackendEmitter, BinKind, ClassDecl, CovergroupDecl, CrvArena, CrvBinaryOp, CrvExpr, CrvUnaryOp,
    ExprId, InsideElem, ScalarKind, TargetCapabilities, UvirError, UvirModule, UvirType, UvmRole,
};

#[derive(Clone, Debug, Default)]
pub struct SvEmitter;

impl SvEmitter {
    pub fn new() -> Self {
        Self
    }

    /// Emits SystemVerilog/UVM code and validates syntax cleanliness via `svlang::Compilation`.
    pub fn emit_and_verify(&self, module: &UvirModule) -> Result<String, UvirError> {
        let sv_text = self.emit(module)?;
        let comp = Compilation::from_source("emitted_uvir.sv", &sv_text);
        let errs: Vec<_> = comp
            .diagnostics()
            .into_iter()
            .filter(|d| {
                if d.severity != Severity::Error {
                    return false;
                }
                match d.stage {
                    DiagnosticStage::Parser => true,
                    DiagnosticStage::Preprocessor => {
                        !d.message.contains("unknown macro or directive `uvm_")
                    }
                    _ => false,
                }
            })
            .collect();
        if !errs.is_empty() {
            return Err(UvirError::new(
                "uvir-emit-sv/verify",
                format!(
                    "emitted SV failed svlang syntax verification at line {}: {}",
                    errs[0].line, errs[0].message
                ),
            ));
        }
        Ok(sv_text)
    }
}

impl BackendEmitter for SvEmitter {
    fn target_name(&self) -> &'static str {
        "sv-uvm"
    }

    fn capabilities(&self) -> TargetCapabilities {
        TargetCapabilities::sv_uvm_1800_2023()
    }

    fn emit(&self, module: &UvirModule) -> Result<String, UvirError> {
        let mut out = String::with_capacity(4096);
        out.push_str(
            "// Generated by uvir (target: sv-uvm / IEEE 1800-2023 + IEEE 1800.2-2020)\n\n",
        );

        for cls in &module.classes {
            emit_sv_class(&mut out, cls, &module.crv_arena)?;
        }
        for cg in &module.standalone_covergroups {
            emit_sv_covergroup(&mut out, cg, "");
            out.push('\n');
        }
        Ok(out)
    }
}

fn emit_sv_class(out: &mut String, cls: &ClassDecl, arena: &CrvArena) -> Result<(), UvirError> {
    let base_sv = match cls.role {
        UvmRole::SequenceItem => "uvm_sequence_item",
        UvmRole::Sequence => "uvm_sequence #(uvm_sequence_item)",
        UvmRole::Reg => "uvm_reg",
        UvmRole::RegBlock => "uvm_reg_block",
        UvmRole::Driver => "uvm_driver #(uvm_sequence_item)",
        UvmRole::Monitor => "uvm_monitor",
        UvmRole::Sequencer => "uvm_sequencer #(uvm_sequence_item)",
        UvmRole::Agent => "uvm_agent",
        UvmRole::Env => "uvm_env",
        UvmRole::Scoreboard => "uvm_scoreboard",
        UvmRole::Subscriber => "uvm_subscriber #(uvm_sequence_item)",
        UvmRole::Test => "uvm_test",
        UvmRole::Component => "uvm_component",
        UvmRole::Object | UvmRole::PlainClass => "uvm_object",
    };

    let _ = writeln!(out, "class {} extends {};", cls.name, base_sv);

    if cls.role == UvmRole::Reg {
        for f in &cls.fields {
            let qual = if f.is_rand { "rand " } else { "" };
            let _ = writeln!(out, "  {}uvm_reg_field {};", qual, f.name);
        }
    } else {
        for f in &cls.fields {
            let qual = if f.is_randc {
                "randc "
            } else if f.is_rand {
                "rand "
            } else {
                ""
            };
            let _ = writeln!(out, "  {}{} {};", qual, format_sv_type(&f.ty), f.name);
        }
    }
    out.push('\n');

    // Factory registration + field policy macros when non-default flags exist
    let has_custom_flags = cls.fields.iter().any(|f| !f.ops.compare || !f.ops.copy);
    if cls.role.is_component() {
        let _ = writeln!(out, "  `uvm_component_utils({})", cls.name);
    } else if has_custom_flags {
        let _ = writeln!(out, "  `uvm_object_utils_begin({})", cls.name);
        for f in &cls.fields {
            let mut flags = Vec::new();
            if !f.ops.compare {
                flags.push("UVM_NOCOMPARE");
            }
            if !f.ops.copy {
                flags.push("UVM_NOCOPY");
            }
            let flag_s = if flags.is_empty() {
                "UVM_ALL_ON".to_string()
            } else {
                flags.join(" | ")
            };
            let _ = writeln!(out, "    `uvm_field_int({}, {})", f.name, flag_s);
        }
        out.push_str("  `uvm_object_utils_end\n");
    } else {
        let _ = writeln!(out, "  `uvm_object_utils({})", cls.name);
    }
    out.push('\n');

    // Constraints
    for cb in &cls.constraints {
        let _ = writeln!(out, "  constraint {} {{", cb.name);
        for cl in &cb.clauses {
            let expr_s = format_sv_expr(cl.expr, arena)?;
            if cl.is_soft {
                let _ = writeln!(out, "    soft {};", expr_s);
            } else {
                let _ = writeln!(out, "    {};", expr_s);
            }
        }
        out.push_str("  }\n\n");
    }

    // Embedded covergroups
    for cg in &cls.covergroups {
        emit_sv_covergroup(out, cg, "  ");
        out.push('\n');
    }

    // Constructor
    if cls.role.is_component() {
        let _ = writeln!(
            out,
            "  function new(string name = \"{}\", uvm_component parent = null);\n    super.new(name, parent);\n  endfunction",
            cls.name
        );
    } else if cls.role == UvmRole::Reg {
        let n_bits = cls.reg_width_bits.unwrap_or(32);
        let _ = writeln!(
            out,
            "  function new(string name = \"{}\");\n    super.new(name, {}, UVM_NO_COVERAGE);\n  endfunction\n",
            cls.name, n_bits
        );
        out.push_str("  virtual function void build();\n");
        for f in &cls.fields {
            if let Some(ral) = &f.ral_meta {
                let _ = writeln!(
                    out,
                    "    {} = uvm_reg_field::type_id::create(\"{}\");",
                    f.name, f.name
                );
                let is_rand_bit = u8::from(f.is_rand);
                let vol_bit = u8::from(ral.volatile);
                let has_rst = u8::from(ral.has_reset);
                let _ = writeln!(
                    out,
                    "    {}.configure(this, {}, {}, \"{}\", {}, {}'h{:X}, {}, {}, 0);",
                    f.name,
                    ral.width,
                    ral.lsb,
                    ral.access,
                    vol_bit,
                    ral.width.max(1),
                    ral.reset,
                    has_rst,
                    is_rand_bit
                );
            }
        }
        out.push_str("  endfunction");
    } else {
        let has_cg = !cls.covergroups.is_empty();
        let _ = writeln!(out, "  function new(string name = \"{}\");", cls.name);
        out.push_str("    super.new(name);\n");
        if has_cg {
            for cg in &cls.covergroups {
                let _ = writeln!(out, "    {} = new();", cg.name);
            }
        }
        out.push_str("  endfunction");
    }
    out.push('\n');

    // Explicit IEEE 1800.2 `do_copy` and `do_compare`
    if cls.synthesize_field_methods && !cls.fields.is_empty() {
        out.push('\n');
        let _ = writeln!(out, "  virtual function void do_copy(uvm_object rhs);");
        let _ = writeln!(out, "    {} rhs_;", cls.name);
        out.push_str("    super.do_copy(rhs);\n");
        out.push_str("    if (!$cast(rhs_, rhs)) return;\n");
        for f in &cls.fields {
            if f.ops.copy {
                let _ = writeln!(out, "    this.{} = rhs_.{};", f.name, f.name);
            }
        }
        out.push_str("  endfunction\n\n");

        out.push_str("  virtual function bit do_compare(uvm_object rhs, uvm_comparer comparer);\n");
        let _ = writeln!(out, "    {} rhs_;", cls.name);
        out.push_str("    if (!$cast(rhs_, rhs)) return 0;\n");
        let mut terms = vec!["super.do_compare(rhs, comparer)".to_string()];
        for f in &cls.fields {
            if f.ops.compare {
                terms.push(format!("(this.{0} == rhs_.{0})", f.name));
            }
        }
        let _ = writeln!(out, "    return {};\n  endfunction", terms.join(" && "));
    }

    out.push_str("endclass\n\n");
    Ok(())
}

fn emit_sv_covergroup(out: &mut String, cg: &CovergroupDecl, indent: &str) {
    let _ = writeln!(out, "{indent}covergroup {};", cg.name);
    for cp in &cg.coverpoints {
        let iff = cp
            .iff_guard
            .as_deref()
            .map(|g| format!(" iff ({g})"))
            .unwrap_or_default();
        if cp.bins.is_empty() {
            let _ = writeln!(
                out,
                "{indent}  {}: coverpoint {}{};",
                cp.name, cp.target_expr, iff
            );
        } else {
            let _ = writeln!(
                out,
                "{indent}  {}: coverpoint {}{} {{",
                cp.name, cp.target_expr, iff
            );
            for b in &cp.bins {
                match &b.kind {
                    BinKind::Range { low, high } => {
                        let _ = writeln!(
                            out,
                            "{indent}    bins {} = {{['h{:X}:'h{:X}]}};",
                            b.name, low, high
                        );
                    }
                    BinKind::IgnoreRange { low, high } => {
                        let _ = writeln!(
                            out,
                            "{indent}    ignore_bins {} = {{['h{:X}:'h{:X}]}};",
                            b.name, low, high
                        );
                    }
                    BinKind::Values(vals) => {
                        let vs: Vec<String> = vals.iter().map(u64::to_string).collect();
                        let _ =
                            writeln!(out, "{indent}    bins {} = {{{}}};", b.name, vs.join(", "));
                    }
                    BinKind::IllegalValues(vals) => {
                        let vs: Vec<String> = vals.iter().map(u64::to_string).collect();
                        let _ = writeln!(
                            out,
                            "{indent}    illegal_bins {} = {{{}}};",
                            b.name,
                            vs.join(", ")
                        );
                    }
                }
            }
            let _ = writeln!(out, "{indent}  }}");
        }
    }
    for cr in &cg.crosses {
        let _ = writeln!(
            out,
            "{indent}  {}: cross {};",
            cr.name,
            cr.coverpoints.join(", ")
        );
    }
    let _ = writeln!(out, "{indent}endgroup");
}

pub fn format_sv_type(ty: &UvirType) -> String {
    match &ty.kind {
        ScalarKind::Bool => "bit".into(),
        ScalarKind::String => "string".into(),
        ScalarKind::Real => "real".into(),
        ScalarKind::ClassRef(c) => c.clone(),
        ScalarKind::LogicVector => {
            let s = if ty.signed { " signed" } else { "" };
            if ty.width == 1 {
                format!("logic{s}")
            } else {
                format!("logic{s} [{}:0]", ty.width - 1)
            }
        }
        ScalarKind::BitVector => {
            let s = if ty.signed { " signed" } else { "" };
            if ty.width == 1 && !ty.signed {
                "bit".into()
            } else {
                format!("bit{s} [{}:0]", ty.width - 1)
            }
        }
    }
}

fn format_sv_expr(id: ExprId, arena: &CrvArena) -> Result<String, UvirError> {
    match arena.get(id) {
        CrvExpr::Var(name) => Ok(name.clone()),
        CrvExpr::BoolConst(b) => Ok(if *b { "1'b1".into() } else { "1'b0".into() }),
        CrvExpr::Const {
            value,
            width,
            signed,
        } => {
            let s = if *signed { "s" } else { "" };
            if *value >= 16 {
                Ok(format!("{width}'{s}h{:X}", value))
            } else {
                Ok(format!("{width}'{s}d{value}"))
            }
        }
        CrvExpr::Unary { op, arg } => {
            let inner = format_sv_expr(*arg, arena)?;
            let pfx = match op {
                CrvUnaryOp::Not => "!",
                CrvUnaryOp::BitNot => "~",
                CrvUnaryOp::Neg => "-",
            };
            Ok(format!("({pfx}{inner})"))
        }
        CrvExpr::Binary { op, lhs, rhs } => {
            let l = format_sv_expr(*lhs, arena)?;
            let r = format_sv_expr(*rhs, arena)?;
            let sym = match op {
                CrvBinaryOp::Eq => "==",
                CrvBinaryOp::Ne => "!=",
                CrvBinaryOp::Lt => "<",
                CrvBinaryOp::Le => "<=",
                CrvBinaryOp::Gt => ">",
                CrvBinaryOp::Ge => ">=",
                CrvBinaryOp::Add => "+",
                CrvBinaryOp::Sub => "-",
                CrvBinaryOp::Mul => "*",
                CrvBinaryOp::Rem => "%",
                CrvBinaryOp::BitAnd => "&",
                CrvBinaryOp::BitOr => "|",
                CrvBinaryOp::BitXor => "^",
                CrvBinaryOp::Shl => "<<",
                CrvBinaryOp::Shr => ">>",
                CrvBinaryOp::LogAnd => "&&",
                CrvBinaryOp::LogOr => "||",
                CrvBinaryOp::Implies => "->",
                CrvBinaryOp::Iff => "<->",
            };
            if matches!(op, CrvBinaryOp::Implies | CrvBinaryOp::Iff) {
                Ok(format!("{l} {sym} {r}"))
            } else {
                Ok(format!("({l} {sym} {r})"))
            }
        }
        CrvExpr::Inside { target, elems } => {
            let t = format_sv_expr(*target, arena)?;
            let mut items = Vec::new();
            for el in elems {
                match el {
                    InsideElem::Single(v) => items.push(format_sv_expr(*v, arena)?),
                    InsideElem::Range { low, high } => {
                        items.push(format!(
                            "[{} : {}]",
                            format_sv_expr(*low, arena)?,
                            format_sv_expr(*high, arena)?
                        ));
                    }
                    InsideElem::ToleranceAbs { center, delta } => {
                        items.push(format!(
                            "[{} +/- {}]",
                            format_sv_expr(*center, arena)?,
                            format_sv_expr(*delta, arena)?
                        ));
                    }
                    InsideElem::TolerancePct { center, pct } => {
                        items.push(format!(
                            "[{} +%- {}]",
                            format_sv_expr(*center, arena)?,
                            format_sv_expr(*pct, arena)?
                        ));
                    }
                }
            }
            Ok(format!("{t} inside {{{}}}", items.join(", ")))
        }
        CrvExpr::Unique { vars } => Ok(format!("unique {{{}}}", vars.join(", "))),
    }
}
