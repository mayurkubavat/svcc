//! Explicit-width SystemVerilog emitter for the typed `svcc_ir::hdl` design IR.
//!
//! The output is not meant to be pretty. It is the form in which a typed design (lowered from
//! SystemVerilog, or lifted from generated SystemC with C++ evaluation rules made explicit) is
//! handed to the `svlang` netlist for equivalence checking, so it must mean exactly what the
//! IR means, independent of SystemVerilog's context-determined sizing:
//!
//! - every signal, port and local is declared unsigned with its exact width; signedness is
//!   applied per operator with `$signed(...)`;
//! - every operator result is wrapped in a concatenation `{...}`, which makes it
//!   self-determined: no operand is ever widened by the context it appears in;
//! - width changes are size casts of such self-determined values;
//! - the two-state rules of the IR are spelled out: division and modulo by zero yield 0,
//!   reads outside a vector or array yield 0, writes outside are dropped;
//! - locals start at 0 on every activation of a process or function.

use std::collections::BTreeSet;
use std::fmt::Write;

use svcc_ir::hdl::{
    BinOp, CaseArm, Design, Dir, Expr, Function, LocalVar, LvBase, Lval, Module, Pat, ProcKind,
    Process, Stmt, Ty, UnOp,
};
use svcc_ir::SvccError;

const STAGE: &str = "svcc-emit-sv/hdl";

/// Emits `design` as explicit-width SystemVerilog. Every module name gets `prefix`, so the
/// text can sit next to the source it was derived from.
pub fn emit_hdl_design_sv(design: &Design, prefix: &str) -> Result<String, SvccError> {
    let mut out = String::new();
    out.push_str(
        "// Generated by svcc: explicit-width two-state SystemVerilog of a typed design.\n",
    );
    let mut errs = Vec::new();
    for m in &design.modules {
        let mut em = Em {
            m,
            prefix,
            errs: Vec::new(),
            temps: Vec::new(),
            ntemp: 0,
            taken: BTreeSet::new(),
            ret: None,
        };
        em.module(&mut out);
        errs.extend(em.errs);
    }
    if errs.is_empty() {
        Ok(out)
    } else {
        Err(SvccError::new(STAGE, errs.join("\n  ")))
    }
}

fn decl(ty: Ty) -> String {
    if ty.w == 1 {
        "logic".to_string()
    } else {
        format!("logic [{}:0]", ty.w - 1)
    }
}

fn hex(words: &[u64], w: u32) -> String {
    let n = w.div_ceil(4) as usize;
    let mut s = String::with_capacity(n);
    for i in (0..n).rev() {
        let bit = i * 4;
        let word = words.get(bit / 64).copied().unwrap_or(0);
        let mut nib = (word >> (bit % 64)) & 0xf;
        let top = w as usize - bit;
        if top < 4 {
            nib &= (1 << top) - 1;
        }
        s.push(char::from_digit(nib as u32, 16).unwrap_or('0'));
    }
    format!("{w}'h{s}")
}

fn lit(v: u64, w: u32) -> String {
    hex(&[v], w)
}

/// Bits needed to hold `v` as an unsigned number.
fn ubits(v: u64) -> u32 {
    (64 - v.leading_zeros()).max(1)
}

/// Return-flag state of a function body being emitted.
struct RetCtx {
    ty: Ty,
    /// The function has a `return` that is not its last statement.
    flagged: bool,
}

struct Em<'a> {
    m: &'a Module,
    prefix: &'a str,
    errs: Vec<String>,
    /// Temporaries of the process or function being emitted.
    temps: Vec<(String, Ty)>,
    ntemp: u32,
    taken: BTreeSet<String>,
    ret: Option<RetCtx>,
}

impl<'a> Em<'a> {
    fn err(&mut self, msg: impl Into<String>) {
        self.errs
            .push(format!("module '{}': {}", self.m.name, msg.into()));
    }

    fn temp(&mut self, ty: Ty) -> String {
        loop {
            let n = format!("svcc__t{}", self.ntemp);
            self.ntemp += 1;
            if self.taken.insert(n.clone()) {
                self.temps.push((n.clone(), ty));
                return n;
            }
        }
    }

    fn dims(&self, name: &str) -> Vec<u32> {
        self.m
            .signals
            .iter()
            .find(|s| s.name == name)
            .map(|s| s.dims.clone())
            .or_else(|| {
                self.m
                    .ports
                    .iter()
                    .find(|p| p.name == name)
                    .map(|p| p.dims.clone())
            })
            .unwrap_or_default()
    }

    // ------------------------------------------------------------------
    // Module
    // ------------------------------------------------------------------

    fn module(&mut self, out: &mut String) {
        let m = self.m;
        let ports: Vec<String> = m
            .ports
            .iter()
            .map(|p| {
                let mut d = format!(
                    "  {} {} {}",
                    match p.dir {
                        Dir::In => "input",
                        Dir::Out => "output",
                    },
                    decl(p.ty),
                    p.name
                );
                for n in &p.dims {
                    let _ = write!(d, " [0:{}]", n.saturating_sub(1));
                }
                d
            })
            .collect();
        let _ = writeln!(out, "module {}{} (", self.prefix, m.name);
        let _ = writeln!(out, "{}", ports.join(",\n"));
        out.push_str(");\n");
        for s in &m.signals {
            let mut d = format!("  {} {}", decl(s.ty), s.name);
            for n in &s.dims {
                let _ = write!(d, " [0:{}]", n.saturating_sub(1));
            }
            if let Some(words) = &s.init {
                if s.dims.is_empty() {
                    let _ = write!(d, " = {}", hex(words, s.ty.w));
                } else {
                    self.err(format!("array '{}' has a start value", s.name));
                }
            }
            let _ = writeln!(out, "{d};");
        }
        for i in &m.instances {
            let conns: Vec<String> = i
                .conns
                .iter()
                .map(|c| {
                    let mut t = c.sig.clone();
                    for e in &c.elem {
                        let _ = write!(t, "[{e}]");
                    }
                    format!(".{}({})", c.port, t)
                })
                .collect();
            let _ = writeln!(
                out,
                "  {}{} {} ({});",
                self.prefix,
                i.module,
                i.name,
                conns.join(", ")
            );
        }
        for f in &m.functions {
            self.function(out, f);
        }
        for p in &m.processes {
            self.process(out, p);
        }
        out.push_str("endmodule\n\n");
    }

    fn begin_scope(&mut self, locals: &[LocalVar], body: &[Stmt], extra: &[LocalVar]) {
        self.temps.clear();
        self.ntemp = 0;
        self.taken = self
            .m
            .ports
            .iter()
            .map(|p| p.name.clone())
            .chain(self.m.signals.iter().map(|s| s.name.clone()))
            .chain(self.m.functions.iter().map(|f| f.name.clone()))
            .collect();
        for l in locals.iter().chain(extra) {
            self.taken.insert(l.name.clone());
        }
        let mut nested = Vec::new();
        collect_block_locals(body, &mut nested);
        for l in nested {
            self.taken.insert(l.name);
        }
    }

    /// All locals of a scope, including those of nested blocks, checked for clashes.
    fn scope_locals(&mut self, locals: &[LocalVar], body: &[Stmt], what: &str) -> Vec<LocalVar> {
        let mut all: Vec<LocalVar> = locals.to_vec();
        collect_block_locals(body, &mut all);
        let mut seen: BTreeSet<&str> = BTreeSet::new();
        let mut dup = Vec::new();
        for l in &all {
            if !seen.insert(l.name.as_str()) {
                dup.push(l.name.clone());
            }
        }
        for d in dup {
            // Same name and type declared in two blocks is one variable here, which is the
            // same thing as long as each block assigns it before reading it. Different types
            // cannot be merged.
            let tys: BTreeSet<(u32, bool)> = all
                .iter()
                .filter(|l| l.name == d)
                .map(|l| (l.ty.w, l.ty.s))
                .collect();
            if tys.len() > 1 {
                self.err(format!(
                    "{what}: local '{d}' is declared with different types in nested blocks"
                ));
            }
        }
        let mut uniq = Vec::new();
        let mut seen = BTreeSet::new();
        for l in all {
            if seen.insert(l.name.clone()) {
                uniq.push(l);
            }
        }
        uniq
    }

    fn function(&mut self, out: &mut String, f: &Function) {
        // `_ret` is the implicit result variable of a function: assigning the function name
        // writes it, a `return e` writes it and ends the call, and falling off the end
        // returns it.
        let ret_var = LocalVar {
            name: "_ret".to_string(),
            ty: f.ret,
        };
        self.begin_scope(&f.locals, &f.body, std::slice::from_ref(&ret_var));
        for a in &f.args {
            self.taken.insert(a.name.clone());
        }
        let mut locals = self.scope_locals(&f.locals, &f.body, &format!("function '{}'", f.name));
        locals.retain(|l| l.name != "_ret");
        locals.insert(0, ret_var);
        // A single `return` as the last statement needs no flag.
        let last_only = matches!(f.body.last(), Some(Stmt::Return(_)))
            && !contains_return(&f.body[..f.body.len() - 1]);
        let flagged = contains_return(&f.body) && !last_only;
        self.ret = Some(RetCtx { ty: f.ret, flagged });
        let mut body = String::new();
        self.stmts(&mut body, &f.body, "    ");
        self.ret = None;

        let args: Vec<String> = f
            .args
            .iter()
            .map(|a| format!("input {} {}", decl(a.ty), a.name))
            .collect();
        let _ = writeln!(
            out,
            "  function automatic {} {}({});",
            decl(f.ret),
            f.name,
            args.join(", ")
        );
        let mut inits = String::new();
        for l in &locals {
            let _ = writeln!(out, "    {} {};", decl(l.ty), l.name);
            let _ = writeln!(inits, "    {} = {};", l.name, lit(0, l.ty.w));
        }
        for (n, ty) in &self.temps {
            let _ = writeln!(out, "    {} {};", decl(*ty), n);
            let _ = writeln!(inits, "    {} = {};", n, lit(0, ty.w));
        }
        if flagged {
            let _ = writeln!(out, "    logic svcc__done;");
            let _ = writeln!(inits, "    svcc__done = 1'h0;");
        }
        out.push_str(&inits);
        out.push_str(&body);
        let _ = writeln!(out, "    return _ret;");
        out.push_str("  endfunction\n");
    }

    fn process(&mut self, out: &mut String, p: &Process) {
        self.begin_scope(&p.locals, &p.body, &[]);
        let locals = self.scope_locals(&p.locals, &p.body, &format!("process '{}'", p.name));
        if contains_return(&p.body) {
            self.err(format!("process '{}' contains a return", p.name));
        }
        let is_seq = matches!(p.kind, ProcKind::Seq { .. });
        if !is_seq && has_nonblocking_sig(&p.body) {
            self.err(format!(
                "combinational process '{}' uses a nonblocking assignment",
                p.name
            ));
        }
        // An edge-triggered block with an asynchronous control must keep the shape
        // `if (ctrl) ... else ...` at its top. Start values of locals, and constant
        // assignments to locals that precede the `if`, go into both branches.
        let mut body = String::new();
        let mut split: Option<(String, String, String)> = None;
        let multi_edge = matches!(&p.kind, ProcKind::Seq { edges } if edges.len() > 1);
        let (lead, rest) = match p.body.iter().position(|s| !is_const_local_assign(s)) {
            Some(k) => p.body.split_at(k),
            None => (&p.body[..], &p.body[..0]),
        };
        match rest {
            [Stmt::If {
                cond,
                then_s,
                else_s,
            }] if multi_edge && plain_ctrl(cond).is_some() => {
                let c = plain_ctrl(cond).unwrap_or_default();
                let mut t = String::new();
                let mut e = String::new();
                self.stmts(&mut t, lead, "      ");
                self.stmts(&mut t, then_s, "      ");
                self.stmts(&mut e, lead, "      ");
                self.stmts(&mut e, else_s, "      ");
                split = Some((c, t, e));
            }
            _ => self.stmts(&mut body, &p.body, "    "),
        }

        let head = match &p.kind {
            ProcKind::Comb => "always @*".to_string(),
            ProcKind::Seq { edges } => {
                let ev: Vec<String> = edges
                    .iter()
                    .map(|e| {
                        format!(
                            "{} {}",
                            if e.posedge { "posedge" } else { "negedge" },
                            e.sig
                        )
                    })
                    .collect();
                format!("always_ff @({})", ev.join(" or "))
            }
        };
        let _ = writeln!(out, "  {head} begin : svcc__p_{}", p.name);
        let mut inits = String::new();
        for l in &locals {
            let _ = writeln!(out, "    {} {};", decl(l.ty), l.name);
            let _ = writeln!(inits, "{} = {};", l.name, lit(0, l.ty.w));
        }
        for (n, ty) in &self.temps {
            let _ = writeln!(out, "    {} {};", decl(*ty), n);
            let _ = writeln!(inits, "{} = {};", n, lit(0, ty.w));
        }
        match split {
            Some((c, t, e)) => {
                let _ = writeln!(out, "    if ({c}) begin");
                for l in inits.lines() {
                    let _ = writeln!(out, "      {l}");
                }
                out.push_str(&t);
                out.push_str("    end else begin\n");
                for l in inits.lines() {
                    let _ = writeln!(out, "      {l}");
                }
                out.push_str(&e);
                out.push_str("    end\n");
            }
            None => {
                for l in inits.lines() {
                    let _ = writeln!(out, "    {l}");
                }
                out.push_str(&body);
            }
        }
        out.push_str("  end\n");
    }

    // ------------------------------------------------------------------
    // Statements
    // ------------------------------------------------------------------

    fn stmts(&mut self, out: &mut String, ss: &[Stmt], ind: &str) {
        let flagged = self.ret.as_ref().is_some_and(|r| r.flagged);
        let mut may_have_returned = false;
        for s in ss {
            if flagged && may_have_returned {
                // Everything after a statement that may return runs only if it did not.
                let ind2 = format!("{ind}  ");
                let _ = writeln!(out, "{ind}if (!svcc__done) begin");
                self.stmt(out, s, &ind2);
                let _ = writeln!(out, "{ind}end");
            } else {
                self.stmt(out, s, ind);
            }
            if contains_return(std::slice::from_ref(s)) {
                may_have_returned = true;
            }
        }
    }

    fn stmt(&mut self, out: &mut String, s: &Stmt, ind: &str) {
        let ind2 = format!("{ind}  ");
        match s {
            Stmt::Assign {
                lhs,
                rhs,
                nonblocking,
            } => self.assign(out, lhs, rhs, *nonblocking, ind),
            Stmt::If {
                cond,
                then_s,
                else_s,
            } => {
                let c = self.truth(cond);
                let _ = writeln!(out, "{ind}if ({c}) begin");
                self.stmts(out, then_s, &ind2);
                if else_s.is_empty() {
                    let _ = writeln!(out, "{ind}end");
                } else {
                    let _ = writeln!(out, "{ind}end else begin");
                    self.stmts(out, else_s, &ind2);
                    let _ = writeln!(out, "{ind}end");
                }
            }
            Stmt::Case { sel, arms, default } => self.case(out, sel, arms, default, ind),
            Stmt::For {
                init,
                cond,
                step,
                body,
            } => {
                let simple = |ss: &[Stmt]| {
                    ss.iter().all(|s| {
                        matches!(
                            s,
                            Stmt::Assign {
                                lhs: Lval {
                                    base: LvBase::Local { .. } | LvBase::Sig { .. },
                                    sel: None
                                },
                                nonblocking: false,
                                ..
                            }
                        )
                    })
                };
                if !simple(init) || !simple(step) || init.is_empty() != step.is_empty() {
                    self.err("for loop whose init or step is not a plain blocking assignment");
                    return;
                }
                let hdr = |em: &mut Self, ss: &[Stmt]| -> String {
                    let mut parts = Vec::new();
                    for s in ss {
                        if let Stmt::Assign {
                            lhs:
                                Lval {
                                    base: LvBase::Local { name, ty } | LvBase::Sig { name, ty },
                                    ..
                                },
                            rhs,
                            ..
                        } = s
                        {
                            parts.push(format!("{} = {}", name, em.fit(rhs, *ty)));
                        }
                    }
                    parts.join(", ")
                };
                let i = hdr(self, init);
                let c = self.truth(cond);
                let st = hdr(self, step);
                let _ = writeln!(out, "{ind}for ({i}; {c}; {st}) begin");
                let flagged = self.ret.as_ref().is_some_and(|r| r.flagged);
                if flagged && contains_return(body) {
                    // The loop keeps its static bound; iterations after a return do nothing.
                    let ind3 = format!("{ind2}  ");
                    let _ = writeln!(out, "{ind2}if (!svcc__done) begin");
                    self.stmts(out, body, &ind3);
                    let _ = writeln!(out, "{ind2}end");
                } else {
                    self.stmts(out, body, &ind2);
                }
                let _ = writeln!(out, "{ind}end");
            }
            Stmt::Return(e) => {
                let Some(rt) = self.ret.as_ref().map(|r| r.ty) else {
                    self.err("return outside a function");
                    return;
                };
                let v = self.fit(e, rt);
                if self.ret.as_ref().is_some_and(|r| r.flagged) {
                    let _ = writeln!(out, "{ind}if (!svcc__done) begin");
                    let _ = writeln!(out, "{ind2}_ret = {v};");
                    let _ = writeln!(out, "{ind2}svcc__done = 1'h1;");
                    let _ = writeln!(out, "{ind}end");
                } else {
                    let _ = writeln!(out, "{ind}_ret = {v};");
                }
            }
            Stmt::Block { locals, body } => {
                // Locals are declared once per process; a block starts its own at 0 again.
                for l in locals {
                    let _ = writeln!(out, "{ind}{} = {};", l.name, lit(0, l.ty.w));
                }
                self.stmts(out, body, ind);
            }
        }
    }

    fn case(
        &mut self,
        out: &mut String,
        sel: &Expr,
        arms: &[CaseArm],
        default: &Option<Vec<Stmt>>,
        ind: &str,
    ) {
        let ty = sel.ty();
        let ind2 = format!("{ind}  ");
        let t = self.temp(Ty::unsigned(ty.w));
        let v = self.ex(sel);
        let _ = writeln!(out, "{ind}{t} = {v};");
        let mut first = true;
        for a in arms {
            let mut tests = Vec::new();
            for p in &a.pats {
                match p {
                    Pat::Const { value, care } => {
                        tests.push(format!(
                            "{{({t} & {}) == {}}}",
                            hex(care, ty.w),
                            hex(value, ty.w)
                        ));
                    }
                    Pat::Expr(e) => {
                        let ev = self.fit(e, Ty::unsigned(ty.w));
                        tests.push(format!("{{{t} == {ev}}}"));
                    }
                    Pat::Range(lo, hi) => {
                        let l = self.fit(lo, ty);
                        let h = self.fit(hi, ty);
                        let (a, b) = if ty.s {
                            (
                                format!("{{$signed({t}) >= $signed({l})}}"),
                                format!("{{$signed({t}) <= $signed({h})}}"),
                            )
                        } else {
                            (format!("{{{t} >= {l}}}"), format!("{{{t} <= {h}}}"))
                        };
                        tests.push(format!("{{{a} & {b}}}"));
                    }
                }
            }
            if tests.is_empty() {
                continue;
            }
            let kw = if first { "if" } else { "end else if" };
            first = false;
            let _ = writeln!(out, "{ind}{kw} ({}) begin", tests.join(" | "));
            self.stmts(out, &a.body, &ind2);
        }
        match default {
            Some(d) if !d.is_empty() => {
                if first {
                    self.stmts(out, d, ind);
                } else {
                    let _ = writeln!(out, "{ind}end else begin");
                    self.stmts(out, d, &ind2);
                    let _ = writeln!(out, "{ind}end");
                }
            }
            _ => {
                if !first {
                    let _ = writeln!(out, "{ind}end");
                }
            }
        }
    }

    fn assign(&mut self, out: &mut String, lhs: &Lval, rhs: &Expr, nonblocking: bool, ind: &str) {
        let op = if nonblocking { "<=" } else { "=" };
        let bty = lhs.base.ty();
        let mut guards: Vec<String> = Vec::new();
        let target = match &lhs.base {
            LvBase::Sig { name, .. } | LvBase::Local { name, .. } => name.clone(),
            LvBase::Elem { name, idx, .. } => {
                let dims = self.dims(name);
                let mut t = name.clone();
                for (k, e) in idx.iter().enumerate() {
                    let d = dims.get(k).copied().unwrap_or(1);
                    let (ix, g) = self.index(e, d);
                    if let Some(g) = g {
                        guards.push(g);
                    }
                    let _ = write!(t, "[{ix}]");
                }
                t
            }
        };
        if matches!(lhs.base, LvBase::Local { .. }) && nonblocking {
            self.err(format!("nonblocking assignment to local '{target}'"));
        }
        let mut lines: Vec<String> = Vec::new();
        match &lhs.sel {
            None => {
                let v = self.fit(rhs, bty);
                lines.push(format!("{target} {op} {v};"));
            }
            Some(sel) if sel.lo_dyn.is_none() => {
                if sel.lo < bty.w && sel.w > 0 {
                    let w = sel.w.min(bty.w - sel.lo);
                    let v = self.fit(rhs, Ty::unsigned(sel.w));
                    let v = if w < sel.w { format!("{w}'({v})") } else { v };
                    if bty.w == 1 {
                        lines.push(format!("{target} {op} {v};"));
                    } else if w == 1 {
                        lines.push(format!("{target}[{}] {op} {v};", sel.lo));
                    } else {
                        lines.push(format!("{target}[{}:{}] {op} {v};", sel.lo + w - 1, sel.lo));
                    }
                }
            }
            Some(sel) => {
                // Position as a signed number wide enough for every case, then one bit at a
                // time: bits that fall outside the target are not written.
                let d = sel.lo_dyn.as_ref().map(|d| d.ty()).unwrap_or(Ty::INT);
                let pw = d.w.max(32) + 3;
                let pty = Ty::unsigned(pw);
                let p = self.temp(pty);
                let t = self.temp(Ty::unsigned(sel.w));
                let pos = self.position(sel.lo, sel.lo_dyn.as_ref(), pw);
                lines.push(format!("{p} = {pos};"));
                let v = self.fit(rhs, Ty::unsigned(sel.w));
                lines.push(format!("{t} = {v};"));
                let iw = ubits(bty.w.saturating_sub(1) as u64);
                for k in 0..sel.w {
                    let pk = format!("{{{p} + {}}}", lit(k as u64, pw));
                    let src = if sel.w == 1 {
                        t.clone()
                    } else {
                        format!("{t}[{k}]")
                    };
                    let dst = if bty.w == 1 {
                        target.clone()
                    } else {
                        format!("{target}[{iw}'({pk})]")
                    };
                    lines.push(format!(
                        "if ({{$signed({pk}) >= $signed({})}} & {{$signed({pk}) < $signed({})}}) {dst} {op} {src};",
                        lit(0, pw),
                        lit(bty.w as u64, pw)
                    ));
                }
            }
        }
        if guards.is_empty() {
            for l in lines {
                let _ = writeln!(out, "{ind}{l}");
            }
        } else {
            let _ = writeln!(out, "{ind}if ({}) begin", guards.join(" & "));
            for l in lines {
                let _ = writeln!(out, "{ind}  {l}");
            }
            let _ = writeln!(out, "{ind}end");
        }
    }

    /// Array index text for dimension size `d`, and the in-range test when it can fail.
    fn index(&mut self, e: &Expr, d: u32) -> (String, Option<String>) {
        let it = e.ty();
        if let Some(c) = e.as_u64() {
            if c < d as u64 {
                return (format!("{c}"), None);
            }
            return ("0".to_string(), Some("1'h0".to_string()));
        }
        let v = self.ex(e);
        let iw = ubits(d.saturating_sub(1) as u64);
        let ix = if it.w == iw {
            v.clone()
        } else {
            format!("{iw}'({v})")
        };
        // Compared as raw bits: a negative signed index is a large unsigned one.
        let cw = it.w.max(ubits(d as u64));
        let guard = if (1u128 << it.w.min(100)) <= d as u128 {
            None
        } else {
            let lhs = if cw == it.w { v } else { format!("{cw}'({v})") };
            Some(format!("{{{lhs} < {}}}", lit(d as u64, cw)))
        };
        (ix, guard)
    }

    /// `lo + lo_dyn` as a `pw`-bit two's-complement value.
    fn position(&mut self, lo: u32, dynp: Option<&Expr>, pw: u32) -> String {
        match dynp {
            None => lit(lo as u64, pw),
            Some(d) => {
                let dv = self.fit(d, Ty::new(pw, d.ty().s));
                if lo == 0 {
                    dv
                } else {
                    format!("{{{dv} + {}}}", lit(lo as u64, pw))
                }
            }
        }
    }

    // ------------------------------------------------------------------
    // Expressions
    // ------------------------------------------------------------------

    /// 1-bit truth value of an expression of any type.
    fn truth(&mut self, e: &Expr) -> String {
        let v = self.ex(e);
        if e.ty().w == 1 {
            v
        } else {
            format!("{{|{v}}}")
        }
    }

    /// Value of `e` converted to `ty` the way an assignment does: widening extends by the
    /// signedness of `e`, narrowing truncates.
    fn fit(&mut self, e: &Expr, ty: Ty) -> String {
        let et = e.ty();
        let v = self.ex(e);
        resize(&v, et, ty.w)
    }

    /// Self-determined, unsigned text of exactly `e.ty().w` bits.
    fn ex(&mut self, e: &Expr) -> String {
        let ty = e.ty();
        let w = ty.w;
        match e {
            Expr::Const { words, .. } => hex(words, w),
            Expr::Sig { name, .. } | Expr::Local { name, .. } => name.clone(),
            Expr::Elem { name, idx, .. } => {
                let dims = self.dims(name);
                let mut t = name.clone();
                let mut guards = Vec::new();
                for (k, i) in idx.iter().enumerate() {
                    let d = dims.get(k).copied().unwrap_or(1);
                    let (ix, g) = self.index(i, d);
                    if let Some(g) = g {
                        guards.push(g);
                    }
                    let _ = write!(t, "[{ix}]");
                }
                if guards.is_empty() {
                    t
                } else {
                    format!("{{({}) ? {t} : {}}}", guards.join(" & "), lit(0, w))
                }
            }
            Expr::Unary { op, arg, .. } => {
                let a = self.ex(arg);
                match op {
                    UnOp::Neg => format!("{{-{a}}}"),
                    UnOp::BitNot => format!("{{~{a}}}"),
                    UnOp::LogNot => format!("{{~(|{a})}}"),
                    UnOp::RedAnd => format!("{{&{a}}}"),
                    UnOp::RedOr => format!("{{|{a}}}"),
                    UnOp::RedXor => format!("{{^{a}}}"),
                }
            }
            Expr::Binary { op, lhs, rhs, .. } => self.binary(*op, lhs, rhs, ty),
            Expr::Cond {
                cond,
                then_e,
                else_e,
                ..
            } => {
                let c = self.truth(cond);
                let a = self.fit(then_e, ty);
                let b = self.fit(else_e, ty);
                format!("{{{c} ? {a} : {b}}}")
            }
            Expr::Concat { parts, .. } => {
                let ps: Vec<String> = parts.iter().map(|p| self.ex(p)).collect();
                let total: u32 = parts.iter().map(|p| p.ty().w).sum();
                let c = format!("{{{}}}", ps.join(", "));
                if total == w {
                    c
                } else {
                    format!("{w}'({c})")
                }
            }
            Expr::Repl { count, arg, .. } => {
                let a = self.ex(arg);
                let total = count * arg.ty().w;
                let c = format!("{{{count}{{{a}}}}}");
                if total == w {
                    c
                } else {
                    format!("{w}'({c})")
                }
            }
            Expr::Slice {
                base, lo, lo_dyn, ..
            } => {
                let bw = base.ty().w;
                let b = self.ex(base);
                let mw = bw.max(w);
                let bm = if mw == bw { b } else { format!("{mw}'({b})") };
                match lo_dyn {
                    None => {
                        if *lo >= bw {
                            lit(0, w)
                        } else if *lo == 0 && w == mw {
                            bm
                        } else {
                            let sh = format!("{{{bm} >> {}}}", lit(*lo as u64, 32));
                            if w == mw {
                                sh
                            } else {
                                format!("{w}'({sh})")
                            }
                        }
                    }
                    Some(d) => {
                        let pw = d.ty().w.max(32) + 3;
                        let p = self.position(*lo, Some(d), pw);
                        let right = format!("{{{bm} >> {p}}}");
                        let left = format!("{{{bm} << {{-{p}}}}}");
                        let pick = format!(
                            "{{{{$signed({p}) < $signed({})}} ? {left} : {right}}}",
                            lit(0, pw)
                        );
                        if w == mw {
                            pick
                        } else {
                            format!("{w}'({pick})")
                        }
                    }
                }
            }
            Expr::Resize { arg, .. } => {
                let a = self.ex(arg);
                resize(&a, arg.ty(), w)
            }
            Expr::Cast { arg, .. } => {
                let a = self.ex(arg);
                resize(&a, Ty::unsigned(arg.ty().w), w)
            }
            Expr::Call { func, args, .. } => {
                let formals: Vec<Ty> = self
                    .m
                    .functions
                    .iter()
                    .find(|f| f.name == *func)
                    .map(|f| f.args.iter().map(|a| a.ty).collect())
                    .unwrap_or_default();
                if formals.len() != args.len() {
                    self.err(format!("call of '{func}' with a wrong number of arguments"));
                }
                let mut cs = Vec::new();
                for (i, a) in args.iter().enumerate() {
                    let fty = formals.get(i).copied().unwrap_or(a.ty());
                    cs.push(self.fit(a, fty));
                }
                format!("{func}({})", cs.join(", "))
            }
            Expr::CountOnes { arg, .. } => {
                let a = self.ex(arg);
                format!("{w}'($countones({a}))")
            }
        }
    }

    fn binary(&mut self, op: BinOp, lhs: &Expr, rhs: &Expr, ty: Ty) -> String {
        let w = ty.w;
        match op {
            BinOp::Add
            | BinOp::Sub
            | BinOp::Mul
            | BinOp::BitAnd
            | BinOp::BitOr
            | BinOp::BitXor
            | BinOp::BitXnor
            | BinOp::Div
            | BinOp::Mod => {
                let a = self.fit(lhs, ty);
                let b = self.fit(rhs, ty);
                let sym = match op {
                    BinOp::Add => "+",
                    BinOp::Sub => "-",
                    BinOp::Mul => "*",
                    BinOp::BitAnd => "&",
                    BinOp::BitOr => "|",
                    BinOp::Div => "/",
                    BinOp::Mod => "%",
                    _ => "^",
                };
                match op {
                    BinOp::BitXnor => format!("{{~({a} ^ {b})}}"),
                    BinOp::Div | BinOp::Mod => {
                        let core = if ty.s {
                            format!("{{$signed({a}) {sym} $signed({b})}}")
                        } else {
                            format!("{{{a} {sym} {b}}}")
                        };
                        format!("{{{{{b} == {}}} ? {} : {core}}}", lit(0, w), lit(0, w))
                    }
                    _ => format!("{{{a} {sym} {b}}}"),
                }
            }
            BinOp::Shl | BinOp::LShr | BinOp::AShr => {
                let a = self.fit(lhs, ty);
                let b = self.ex(rhs);
                match op {
                    BinOp::Shl => format!("{{{a} << {b}}}"),
                    BinOp::AShr if ty.s => format!("{{$signed({a}) >>> {b}}}"),
                    _ => format!("{{{a} >> {b}}}"),
                }
            }
            BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => {
                let ot = lhs.ty();
                let a = self.ex(lhs);
                let b = self.fit(rhs, ot);
                let sym = match op {
                    BinOp::Eq => "==",
                    BinOp::Ne => "!=",
                    BinOp::Lt => "<",
                    BinOp::Le => "<=",
                    BinOp::Gt => ">",
                    _ => ">=",
                };
                if rhs.ty() != ot {
                    self.err("comparison of operands with different types");
                }
                if ot.s && !matches!(op, BinOp::Eq | BinOp::Ne) {
                    format!("{{$signed({a}) {sym} $signed({b})}}")
                } else {
                    format!("{{{a} {sym} {b}}}")
                }
            }
            BinOp::LogAnd | BinOp::LogOr => {
                let a = self.truth(lhs);
                let b = self.truth(rhs);
                let sym = if op == BinOp::LogAnd { "&" } else { "|" };
                format!("{{{a} {sym} {b}}}")
            }
        }
    }
}

/// `v` (self-determined, `from.w` bits) as `w` bits: extended by the signedness of `from`.
fn resize(v: &str, from: Ty, w: u32) -> String {
    if from.w == w {
        v.to_string()
    } else if w < from.w || !from.s {
        format!("{w}'({v})")
    } else {
        format!("{{{w}'($signed({v}))}}")
    }
}

/// `r`, `!r` or `~r` for a 1-bit signal `r`: the only condition shapes a netlist accepts for
/// an asynchronous control.
fn plain_ctrl(e: &Expr) -> Option<String> {
    fn sig(e: &Expr) -> Option<&str> {
        match e {
            Expr::Sig { name, ty } if ty.w == 1 => Some(name),
            Expr::Resize { arg, ty } | Expr::Cast { arg, ty } if ty.w == 1 => sig(arg),
            _ => None,
        }
    }
    match e {
        Expr::Unary {
            op: UnOp::LogNot | UnOp::BitNot,
            arg,
            ..
        } => sig(arg).map(|n| format!("!{n}")),
        Expr::Binary {
            op: BinOp::Eq,
            lhs,
            rhs,
            ..
        } if rhs.as_u64() == Some(0) => sig(lhs).map(|n| format!("!{n}")),
        Expr::Binary {
            op: BinOp::Ne,
            lhs,
            rhs,
            ..
        } if rhs.as_u64() == Some(0) => sig(lhs).map(str::to_string),
        Expr::Binary {
            op: BinOp::Eq,
            lhs,
            rhs,
            ..
        } if rhs.as_u64() == Some(1) => sig(lhs).map(str::to_string),
        _ => sig(e).map(str::to_string),
    }
}

fn is_const_local_assign(s: &Stmt) -> bool {
    matches!(
        s,
        Stmt::Assign {
            lhs: Lval {
                base: LvBase::Local { .. },
                sel: None
            },
            rhs: Expr::Const { .. },
            nonblocking: false,
        }
    )
}

fn collect_block_locals(ss: &[Stmt], out: &mut Vec<LocalVar>) {
    for s in ss {
        match s {
            Stmt::If { then_s, else_s, .. } => {
                collect_block_locals(then_s, out);
                collect_block_locals(else_s, out);
            }
            Stmt::Case { arms, default, .. } => {
                for a in arms {
                    collect_block_locals(&a.body, out);
                }
                if let Some(d) = default {
                    collect_block_locals(d, out);
                }
            }
            Stmt::For { body, .. } => collect_block_locals(body, out),
            Stmt::Block { locals, body } => {
                out.extend(locals.iter().cloned());
                collect_block_locals(body, out);
            }
            Stmt::Assign { .. } | Stmt::Return(_) => {}
        }
    }
}

fn contains_return(ss: &[Stmt]) -> bool {
    ss.iter().any(|s| match s {
        Stmt::Return(_) => true,
        Stmt::If { then_s, else_s, .. } => contains_return(then_s) || contains_return(else_s),
        Stmt::Case { arms, default, .. } => {
            arms.iter().any(|a| contains_return(&a.body))
                || default.as_ref().is_some_and(|d| contains_return(d))
        }
        Stmt::For { body, .. } => contains_return(body),
        Stmt::Block { body, .. } => contains_return(body),
        Stmt::Assign { .. } => false,
    })
}

fn has_nonblocking_sig(ss: &[Stmt]) -> bool {
    ss.iter().any(|s| match s {
        Stmt::Assign {
            lhs, nonblocking, ..
        } => *nonblocking && !matches!(lhs.base, LvBase::Local { .. }),
        Stmt::If { then_s, else_s, .. } => {
            has_nonblocking_sig(then_s) || has_nonblocking_sig(else_s)
        }
        Stmt::Case { arms, default, .. } => {
            arms.iter().any(|a| has_nonblocking_sig(&a.body))
                || default.as_ref().is_some_and(|d| has_nonblocking_sig(d))
        }
        Stmt::For { body, .. } => has_nonblocking_sig(body),
        Stmt::Block { body, .. } => has_nonblocking_sig(body),
        Stmt::Return(_) => false,
    })
}
