//! IEEE 1800-2023 SystemVerilog & IEEE 1800.2-2020 UVM backend emitter for `svcc-ir`.

pub mod hdl_emit;

use std::collections::BTreeSet;
use std::fmt::Write;
use svcc_ir::{
    BackendEmitter, BinKind, ClassDecl, ClockingDecl, CovergroupDecl, CrvArena, CrvBinaryOp,
    CrvExpr, CrvUnaryOp, DistWeightKind, EnumDecl, ExprId, InsideElem, IrModule, IrType, JoinKind,
    ScalarKind, SchedOp, SvaPropertyDecl, SvccError, TargetCapabilities, TlmPortKind, UvmRole,
};
#[cfg(feature = "verify-svlang")]
use svcc_svlang::{verify_emitted_sv, EmittedSvError};

#[derive(Clone, Debug, Default)]
pub struct SvEmitter;

impl SvEmitter {
    pub fn new() -> Self {
        Self
    }

    /// Synthesizes `InFormal` D17-compliant primary-input `assume property` directives from a
    /// `ClassDecl`'s hard CRV constraints (`check_sec(assumptions=[...])`).
    pub fn emit_d17_primary_input_assumptions(
        &self,
        cls: &ClassDecl,
        arena: &CrvArena,
        clock: &str,
        disable_iff: Option<&str>,
    ) -> Result<Vec<String>, SvccError> {
        let dis = disable_iff
            .map(|d| format!(" disable iff ({d})"))
            .unwrap_or_default();
        let mut out = Vec::new();
        for cb in &cls.constraints {
            for (idx, clause) in cb.clauses.iter().enumerate() {
                if !clause.is_soft {
                    let pred = format_sv_expr(clause.expr, arena)?;
                    out.push(format!(
                        "svcc_d17_{}_{}: assume property (@(posedge {}){} ({}));",
                        cb.name, idx, clock, dis, pred
                    ));
                }
            }
        }
        Ok(out)
    }

    pub fn emit_and_verify(&self, module: &IrModule) -> Result<String, SvccError> {
        let sv_text = self.emit(module)?;
        #[cfg(feature = "verify-svlang")]
        {
            let has_uvm_classes = !module.classes.is_empty();
            match verify_emitted_sv("emitted_svcc.sv", &sv_text, has_uvm_classes) {
                Ok(()) => {}
                Err(EmittedSvError::Diagnostic { line, message }) => {
                    return Err(SvccError::new(
                        "svcc-emit-sv/verify",
                        format!("emitted SV failed svlang verification at line {line}: {message}"),
                    ));
                }
                Err(EmittedSvError::Lint {
                    rule,
                    line,
                    message,
                }) => {
                    return Err(SvccError::new(
                        "svcc-emit-sv/svlang-lint",
                        format!("emitted SV failed svlang-lint [{rule}] at line {line}: {message}"),
                    ));
                }
            }
        }
        Ok(sv_text)
    }
}

impl BackendEmitter for SvEmitter {
    fn target_name(&self) -> &'static str {
        "sv-uvm"
    }

    fn capabilities(&self) -> TargetCapabilities {
        TargetCapabilities::sv_uvm_1800_2023()
    }

    fn emit(&self, module: &IrModule) -> Result<String, SvccError> {
        let mut out = String::with_capacity(8192);
        out.push_str(
            "// Generated by svcc (target: sv-uvm / IEEE 1800-2023 + IEEE 1800.2-2020)\n\n",
        );

        for en in &module.enums {
            emit_sv_enum(&mut out, en);
        }
        for cb in &module.clockings {
            emit_sv_clocking_interface(&mut out, cb);
        }
        for cls in &module.classes {
            emit_sv_class(&mut out, cls, &module.crv_arena)?;
        }
        for cg in &module.standalone_covergroups {
            emit_sv_covergroup(&mut out, cg, "");
            out.push('\n');
        }
        if !module.properties.is_empty() {
            emit_sv_sva_wrapper(&mut out, &module.properties);
        }
        Ok(out)
    }
}

fn emit_sv_enum(out: &mut String, en: &EnumDecl) {
    let w = en.width.max(1);
    let _ = writeln!(out, "typedef enum bit [{}:0] {{", w - 1);
    for (i, (vname, vval)) in en.variants.iter().enumerate() {
        let comma = if i + 1 < en.variants.len() { "," } else { "" };
        let _ = writeln!(out, "  {} = {}'d{}{}", vname, w, vval, comma);
    }
    let _ = writeln!(out, "}} {};\n", en.name);
}

fn emit_sv_clocking_interface(out: &mut String, cb: &ClockingDecl) {
    let _ = writeln!(
        out,
        "interface svcc_if_{}(input logic {});",
        cb.name, cb.clock_signal
    );
    for s in cb
        .input_1step_signals
        .iter()
        .chain(cb.output_signals.iter())
    {
        let _ = writeln!(out, "  logic {};", s);
    }
    let _ = writeln!(
        out,
        "  clocking {} @(posedge {});",
        cb.name, cb.clock_signal
    );
    out.push_str("    default input #1step output #0;\n");
    for s in &cb.input_1step_signals {
        let _ = writeln!(out, "    input {};", s);
    }
    for s in &cb.output_signals {
        let _ = writeln!(out, "    output {};", s);
    }
    out.push_str("  endclocking\nendinterface\n\n");
}

fn collect_sv_ident_tokens(expr: &str, out: &mut BTreeSet<String>) {
    let mut cur = String::new();
    for ch in expr.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' || ch == '$' {
            cur.push(ch);
        } else {
            if !cur.is_empty() {
                if !cur.starts_with('$')
                    && !cur.chars().next().unwrap().is_ascii_digit()
                    && !matches!(
                        cur.as_str(),
                        "posedge" | "negedge" | "and" | "or" | "not" | "iff" | "true" | "false"
                    )
                {
                    out.insert(cur.clone());
                }
                cur.clear();
            }
        }
    }
    if !cur.is_empty()
        && !cur.starts_with('$')
        && !cur.chars().next().unwrap().is_ascii_digit()
        && !matches!(
            cur.as_str(),
            "posedge" | "negedge" | "and" | "or" | "not" | "iff" | "true" | "false"
        )
    {
        out.insert(cur);
    }
}

fn emit_sv_sva_wrapper(out: &mut String, props: &[SvaPropertyDecl]) {
    let mut sigs = BTreeSet::new();
    for p in props {
        collect_sv_ident_tokens(&p.clock_signal, &mut sigs);
        if let Some(d) = &p.disable_iff {
            collect_sv_ident_tokens(d, &mut sigs);
        }
        collect_sv_ident_tokens(&p.antecedent, &mut sigs);
        collect_sv_ident_tokens(&p.consequent, &mut sigs);
    }
    if sigs.is_empty() {
        sigs.insert("clk".to_string());
    }
    let port_list: Vec<String> = sigs.iter().map(|s| format!("input logic {s}")).collect();
    let _ = writeln!(out, "module svcc_sva_assertions({});", port_list.join(", "));
    for p in props {
        let kw = if p.is_cover { "cover" } else { "assert" };
        let dis = p
            .disable_iff
            .as_deref()
            .map(|d| format!(" disable iff ({d})"))
            .unwrap_or_default();
        let delay = if p.min_delay == 0 && p.max_delay == 0 {
            String::new()
        } else if p.min_delay == p.max_delay {
            format!("##{} ", p.min_delay)
        } else {
            format!("##[{}:{}] ", p.min_delay, p.max_delay)
        };
        let _ = writeln!(
            out,
            "  {}: {} property (@(posedge {}){} {} |-> {}{});",
            p.name, kw, p.clock_signal, dis, p.antecedent, delay, p.consequent
        );
    }
    out.push_str("endmodule\n\n");
}

fn emit_sv_class(out: &mut String, cls: &ClassDecl, arena: &CrvArena) -> Result<(), SvccError> {
    let item_ty = cls.item_type.as_deref().unwrap_or("uvm_sequence_item");
    let base_sv = match cls.role {
        UvmRole::SequenceItem => "uvm_sequence_item".to_string(),
        UvmRole::Sequence => format!("uvm_sequence #({item_ty})"),
        UvmRole::Reg => "uvm_reg".to_string(),
        UvmRole::RegBlock => "uvm_reg_block".to_string(),
        UvmRole::Driver => format!("uvm_driver #({item_ty})"),
        UvmRole::Monitor => "uvm_monitor".to_string(),
        UvmRole::Sequencer => format!("uvm_sequencer #({item_ty})"),
        UvmRole::Agent => "uvm_agent".to_string(),
        UvmRole::Env => "uvm_env".to_string(),
        UvmRole::Scoreboard => "uvm_scoreboard".to_string(),
        UvmRole::Subscriber => format!("uvm_subscriber #({item_ty})"),
        UvmRole::Test => "uvm_test".to_string(),
        UvmRole::Component => "uvm_component".to_string(),
        UvmRole::Object | UvmRole::PlainClass => "uvm_object".to_string(),
    };

    let _ = writeln!(out, "class {} extends {};", cls.name, base_sv);

    if let Some(rmap) = &cls.ral_map {
        for r in &rmap.registers {
            let _ = writeln!(out, "  rand {} {};", r.class_name, r.inst_name);
        }
    }

    for sub in &cls.subcomponents {
        let _ = writeln!(out, "  {} {};", sub.class_name, sub.name);
    }
    for port in &cls.tlm_ports {
        let pty = match port.kind {
            TlmPortKind::AnalysisPort => format!("uvm_analysis_port #({})", port.item_type),
            TlmPortKind::AnalysisExport => format!("uvm_analysis_export #({})", port.item_type),
            TlmPortKind::SeqItemPullPort => {
                format!("uvm_seq_item_pull_port #({})", port.item_type)
            }
        };
        let _ = writeln!(out, "  {} {};", pty, port.name);
    }

    if cls.role == UvmRole::Reg {
        for f in &cls.fields {
            let qual = if f.is_rand { "rand " } else { "" };
            let _ = writeln!(out, "  {}uvm_reg_field {};", qual, f.name);
        }
    } else {
        for f in &cls.fields {
            let qual = if f.is_randc {
                "randc "
            } else if f.is_rand {
                "rand "
            } else {
                ""
            };
            let _ = writeln!(out, "  {}{} {};", qual, format_sv_type(&f.ty), f.name);
        }
    }
    out.push('\n');

    let has_custom_flags = cls.fields.iter().any(|f| !f.ops.compare || !f.ops.copy);
    if cls.role.is_component() {
        let _ = writeln!(out, "  `uvm_component_utils({})", cls.name);
    } else if has_custom_flags {
        let _ = writeln!(out, "  `uvm_object_utils_begin({})", cls.name);
        for f in &cls.fields {
            let mut flags = Vec::new();
            if !f.ops.compare {
                flags.push("UVM_NOCOMPARE");
            }
            if !f.ops.copy {
                flags.push("UVM_NOCOPY");
            }
            let flag_s = if flags.is_empty() {
                "UVM_ALL_ON".to_string()
            } else {
                flags.join(" | ")
            };
            let _ = writeln!(out, "    `uvm_field_int({}, {})", f.name, flag_s);
        }
        out.push_str("  `uvm_object_utils_end\n");
    } else {
        let _ = writeln!(out, "  `uvm_object_utils({})", cls.name);
    }
    out.push('\n');

    for cb in &cls.constraints {
        let _ = writeln!(out, "  constraint {} {{", cb.name);
        for cl in &cb.clauses {
            let expr_s = format_sv_expr(cl.expr, arena)?;
            if cl.is_soft {
                let _ = writeln!(out, "    soft {};", expr_s);
            } else {
                let _ = writeln!(out, "    {};", expr_s);
            }
        }
        out.push_str("  }\n\n");
    }

    for cg in &cls.covergroups {
        emit_sv_covergroup(out, cg, "  ");
        out.push('\n');
    }

    // Constructor & RAL `build()`
    if cls.role.is_component() {
        let _ = writeln!(
            out,
            "  function new(string name = \"{}\", uvm_component parent = null);\n    super.new(name, parent);\n  endfunction",
            cls.name
        );
    } else if cls.role == UvmRole::Reg {
        let n_bits = cls.reg_width_bits.unwrap_or(32);
        let _ = writeln!(
            out,
            "  function new(string name = \"{}\");\n    super.new(name, {}, UVM_NO_COVERAGE);\n  endfunction\n",
            cls.name, n_bits
        );
        out.push_str("  virtual function void build();\n");
        for f in &cls.fields {
            if let Some(ral) = &f.ral_meta {
                let _ = writeln!(
                    out,
                    "    {} = uvm_reg_field::type_id::create(\"{}\");",
                    f.name, f.name
                );
                let is_rand_bit = u8::from(f.is_rand);
                let vol_bit = u8::from(ral.volatile);
                let has_rst = u8::from(ral.has_reset);
                let _ = writeln!(
                    out,
                    "    {}.configure(this, {}, {}, \"{}\", {}, {}'h{:X}, {}, {}, 0);",
                    f.name,
                    ral.width,
                    ral.lsb,
                    ral.access,
                    vol_bit,
                    ral.width.max(1),
                    ral.reset,
                    has_rst,
                    is_rand_bit
                );
            }
        }
        out.push_str("  endfunction");
    } else if cls.role == UvmRole::RegBlock {
        let _ = writeln!(
            out,
            "  function new(string name = \"{}\");\n    super.new(name, UVM_NO_COVERAGE);\n  endfunction\n",
            cls.name
        );
        if let Some(rmap) = &cls.ral_map {
            out.push_str("  virtual function void build();\n");
            for r in &rmap.registers {
                let _ = writeln!(
                    out,
                    "    {0} = {1}::type_id::create(\"{0}\");\n    {0}.configure(this);\n    {0}.build();",
                    r.inst_name, r.class_name
                );
            }
            let _ = writeln!(
                out,
                "    default_map = create_map(\"{}\", 'h{:X}, {}, UVM_LITTLE_ENDIAN);",
                rmap.map_name, rmap.base_addr, rmap.addr_unit_bytes
            );
            for r in &rmap.registers {
                let _ = writeln!(
                    out,
                    "    default_map.add_reg({}, 'h{:X}, \"{}\");",
                    r.inst_name, r.offset, r.rights
                );
            }
            out.push_str("  endfunction");
        }
    } else {
        let _ = writeln!(out, "  function new(string name = \"{}\");", cls.name);
        out.push_str("    super.new(name);\n");
        for cg in &cls.covergroups {
            let _ = writeln!(out, "    {} = new();", cg.name);
        }
        out.push_str("  endfunction");
    }
    out.push('\n');

    if !cls.subcomponents.is_empty() || !cls.tlm_ports.is_empty() {
        out.push_str("\n  virtual function void build_phase(uvm_phase phase);\n");
        out.push_str("    super.build_phase(phase);\n");
        for sub in &cls.subcomponents {
            let _ = writeln!(
                out,
                "    {0} = {1}::type_id::create(\"{0}\", this);",
                sub.name, sub.class_name
            );
        }
        for port in &cls.tlm_ports {
            let _ = writeln!(out, "    {0} = new(\"{0}\", this);", port.name);
        }
        out.push_str("  endfunction\n");
    }

    if !cls.tlm_connections.is_empty() {
        out.push_str("\n  virtual function void connect_phase(uvm_phase phase);\n");
        out.push_str("    super.connect_phase(phase);\n");
        for conn in &cls.tlm_connections {
            let _ = writeln!(out, "    {}.connect({});", conn.initiator, conn.target);
        }
        out.push_str("  endfunction\n");
    }

    for m in &cls.methods {
        if m.body_ops.is_empty() {
            continue;
        }
        out.push('\n');
        if m.name == "body" && cls.role == UvmRole::Sequence {
            out.push_str("  virtual task body();\n");
            emit_sv_sched_ops(out, &m.body_ops, "    ");
            out.push_str("  endtask\n");
        } else if m.is_task {
            let _ = writeln!(out, "  virtual task {}(uvm_phase phase);", m.name);
            emit_sv_sched_ops(out, &m.body_ops, "    ");
            out.push_str("  endtask\n");
        }
    }

    if cls.synthesize_field_methods && !cls.fields.is_empty() {
        out.push('\n');
        out.push_str("  virtual function void do_copy(uvm_object rhs);\n");
        let _ = writeln!(out, "    {} rhs_;", cls.name);
        out.push_str("    super.do_copy(rhs);\n");
        out.push_str("    if (!$cast(rhs_, rhs)) return;\n");
        for f in &cls.fields {
            if f.ops.copy {
                let _ = writeln!(out, "    this.{} = rhs_.{};", f.name, f.name);
            }
        }
        out.push_str("  endfunction\n\n");

        out.push_str("  virtual function bit do_compare(uvm_object rhs, uvm_comparer comparer);\n");
        let _ = writeln!(out, "    {} rhs_;", cls.name);
        out.push_str("    if (!$cast(rhs_, rhs)) return 0;\n");
        let mut terms = vec!["super.do_compare(rhs, comparer)".to_string()];
        for f in &cls.fields {
            if f.ops.compare {
                terms.push(format!("(this.{0} == rhs_.{0})", f.name));
            }
        }
        let _ = writeln!(out, "    return {};\n  endfunction", terms.join(" && "));
    }

    out.push_str("endclass\n\n");
    Ok(())
}

fn emit_sv_sched_ops(out: &mut String, ops: &[SchedOp], indent: &str) {
    for op in ops {
        match op {
            SchedOp::WaitPosEdge { signal } => {
                let _ = writeln!(out, "{indent}@(posedge {signal});");
            }
            SchedOp::WaitDelayNs { ns } => {
                let _ = writeln!(out, "{indent}#{ns}ns;");
            }
            SchedOp::SamplePreTimestep { clocking_name } => {
                let _ = writeln!(out, "{indent}@({clocking_name});");
            }
            SchedOp::Fork {
                join,
                branches,
                cancel_on_exit,
            } => {
                let _ = writeln!(out, "{indent}fork");
                for br in branches {
                    let _ = writeln!(out, "{indent}  begin");
                    emit_sv_sched_ops(out, br, &format!("{indent}    "));
                    let _ = writeln!(out, "{indent}  end");
                }
                let jkw = match join {
                    JoinKind::JoinAll => "join",
                    JoinKind::JoinAny => "join_any",
                    JoinKind::JoinNone => "join_none",
                };
                let _ = writeln!(out, "{indent}{jkw}");
                if *cancel_on_exit {
                    let _ = writeln!(out, "{indent}disable fork;");
                }
            }
            SchedOp::DisableFork => {
                let _ = writeln!(out, "{indent}disable fork;");
            }
            SchedOp::WaitFork => {
                let _ = writeln!(out, "{indent}wait fork;");
            }
            SchedOp::StartItem { item_var } => {
                let _ = writeln!(out, "{indent}start_item({item_var});");
            }
            SchedOp::RandomizeItem { item_var } => {
                let _ = writeln!(out, "{indent}void'({item_var}.randomize());");
            }
            SchedOp::FinishItem { item_var } => {
                let _ = writeln!(out, "{indent}finish_item({item_var});");
            }
            SchedOp::AnalysisWrite { port, expr } => {
                let _ = writeln!(out, "{indent}{port}.write({expr});");
            }
            SchedOp::Repeat { count, body } => {
                let _ = writeln!(out, "{indent}repeat ({count}) begin");
                emit_sv_sched_ops(out, body, &format!("{indent}  "));
                let _ = writeln!(out, "{indent}end");
            }
            SchedOp::Assign {
                lhs,
                rhs,
                nonblocking,
            } => {
                let op_s = if *nonblocking { "<=" } else { "=" };
                let _ = writeln!(out, "{indent}{lhs} {op_s} {rhs};");
            }
            SchedOp::Call { stmt } => {
                let _ = writeln!(out, "{indent}{stmt};");
            }
        }
    }
}

fn emit_sv_covergroup(out: &mut String, cg: &CovergroupDecl, indent: &str) {
    let _ = writeln!(out, "{indent}covergroup {};", cg.name);
    for cp in &cg.coverpoints {
        let iff = cp
            .iff_guard
            .as_deref()
            .map(|g| format!(" iff ({g})"))
            .unwrap_or_default();
        if cp.bins.is_empty() {
            let _ = writeln!(
                out,
                "{indent}  {}: coverpoint {}{};",
                cp.name, cp.target_expr, iff
            );
        } else {
            let _ = writeln!(
                out,
                "{indent}  {}: coverpoint {}{} {{",
                cp.name, cp.target_expr, iff
            );
            for b in &cp.bins {
                match &b.kind {
                    BinKind::Range { low, high } => {
                        let _ = writeln!(
                            out,
                            "{indent}    bins {} = {{['h{:X}:'h{:X}]}};",
                            b.name, low, high
                        );
                    }
                    BinKind::IgnoreRange { low, high } => {
                        let _ = writeln!(
                            out,
                            "{indent}    ignore_bins {} = {{['h{:X}:'h{:X}]}};",
                            b.name, low, high
                        );
                    }
                    BinKind::Values(vals) => {
                        let vs: Vec<String> = vals.iter().map(u64::to_string).collect();
                        let _ =
                            writeln!(out, "{indent}    bins {} = {{{}}};", b.name, vs.join(", "));
                    }
                    BinKind::IllegalValues(vals) => {
                        let vs: Vec<String> = vals.iter().map(u64::to_string).collect();
                        let _ = writeln!(
                            out,
                            "{indent}    illegal_bins {} = {{{}}};",
                            b.name,
                            vs.join(", ")
                        );
                    }
                }
            }
            let _ = writeln!(out, "{indent}  }}");
        }
    }
    for cr in &cg.crosses {
        let _ = writeln!(
            out,
            "{indent}  {}: cross {};",
            cr.name,
            cr.coverpoints.join(", ")
        );
    }
    let _ = writeln!(out, "{indent}endgroup");
}

pub fn format_sv_type(ty: &IrType) -> String {
    match &ty.kind {
        ScalarKind::Bool => "bit".into(),
        ScalarKind::String => "string".into(),
        ScalarKind::Real => "real".into(),
        ScalarKind::Enum(ename) => ename.clone(),
        ScalarKind::ClassRef(c) => c.clone(),
        ScalarKind::LogicVector => {
            let s = if ty.signed { " signed" } else { "" };
            if ty.width == 1 {
                format!("logic{s}")
            } else {
                format!("logic{s} [{}:0]", ty.width - 1)
            }
        }
        ScalarKind::BitVector => {
            let s = if ty.signed { " signed" } else { "" };
            if ty.width == 1 && !ty.signed {
                "bit".into()
            } else {
                format!("bit{s} [{}:0]", ty.width - 1)
            }
        }
    }
}

fn format_sv_inside_elem(el: &InsideElem, arena: &CrvArena) -> Result<String, SvccError> {
    match el {
        InsideElem::Single(v) => format_sv_expr(*v, arena),
        InsideElem::Range { low, high } => Ok(format!(
            "[{} : {}]",
            format_sv_expr(*low, arena)?,
            format_sv_expr(*high, arena)?
        )),
        InsideElem::ToleranceAbs { center, delta } => Ok(format!(
            "[{} +/- {}]",
            format_sv_expr(*center, arena)?,
            format_sv_expr(*delta, arena)?
        )),
        InsideElem::TolerancePct { center, pct } => Ok(format!(
            "[{} +%- {}]",
            format_sv_expr(*center, arena)?,
            format_sv_expr(*pct, arena)?
        )),
    }
}

fn format_sv_expr(id: ExprId, arena: &CrvArena) -> Result<String, SvccError> {
    match arena.get(id) {
        CrvExpr::Var(name) => Ok(name.clone()),
        CrvExpr::BoolConst(b) => Ok(if *b { "1'b1".into() } else { "1'b0".into() }),
        CrvExpr::Const {
            value,
            width,
            signed,
        } => {
            let s = if *signed { "s" } else { "" };
            if *value >= 16 {
                Ok(format!("{width}'{s}h{:X}", value))
            } else {
                Ok(format!("{width}'{s}d{value}"))
            }
        }
        CrvExpr::Unary { op, arg } => {
            let inner = format_sv_expr(*arg, arena)?;
            let pfx = match op {
                CrvUnaryOp::Not => "!",
                CrvUnaryOp::BitNot => "~",
                CrvUnaryOp::Neg => "-",
            };
            Ok(format!("({pfx}{inner})"))
        }
        CrvExpr::Binary { op, lhs, rhs } => {
            let l = format_sv_expr(*lhs, arena)?;
            let r = format_sv_expr(*rhs, arena)?;
            let sym = match op {
                CrvBinaryOp::Eq => "==",
                CrvBinaryOp::Ne => "!=",
                CrvBinaryOp::Lt => "<",
                CrvBinaryOp::Le => "<=",
                CrvBinaryOp::Gt => ">",
                CrvBinaryOp::Ge => ">=",
                CrvBinaryOp::Add => "+",
                CrvBinaryOp::Sub => "-",
                CrvBinaryOp::Mul => "*",
                CrvBinaryOp::Rem => "%",
                CrvBinaryOp::BitAnd => "&",
                CrvBinaryOp::BitOr => "|",
                CrvBinaryOp::BitXor => "^",
                CrvBinaryOp::Shl => "<<",
                CrvBinaryOp::Shr => ">>",
                CrvBinaryOp::LogAnd => "&&",
                CrvBinaryOp::LogOr => "||",
                CrvBinaryOp::Implies => "->",
                CrvBinaryOp::Iff => "<->",
            };
            if matches!(op, CrvBinaryOp::Implies | CrvBinaryOp::Iff) {
                Ok(format!("{l} {sym} {r}"))
            } else {
                Ok(format!("({l} {sym} {r})"))
            }
        }
        CrvExpr::Inside { target, elems } => {
            let t = format_sv_expr(*target, arena)?;
            let mut items = Vec::new();
            for el in elems {
                items.push(format_sv_inside_elem(el, arena)?);
            }
            Ok(format!("{t} inside {{{}}}", items.join(", ")))
        }
        CrvExpr::Dist { target, items } => {
            let t = format_sv_expr(*target, arena)?;
            let mut out_items = Vec::new();
            for it in items {
                let elem_s = format_sv_inside_elem(&it.elem, arena)?;
                let op_s = match it.kind {
                    DistWeightKind::PerValue => ":=",
                    DistWeightKind::SplitRange => ":/",
                };
                out_items.push(format!("{elem_s} {op_s} {}", it.weight));
            }
            Ok(format!("{t} dist {{{}}}", out_items.join(", ")))
        }
        CrvExpr::Unique { vars } => Ok(format!("unique {{{}}}", vars.join(", "))),
    }
}
