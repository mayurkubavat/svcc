#!/usr/bin/env python3
"""Maintain the related-work library in references/.

references/papers.toml is the single source of truth. This script derives
everything else from it:

  python3 scripts/refs.py check   # validate papers.toml (keys, fields, sections)
  python3 scripts/refs.py index   # regenerate references/INDEX.md
  python3 scripts/refs.py bib     # regenerate references/survey.bib
  python3 scripts/refs.py fetch   # download open-access PDFs into references/pdfs/
  python3 scripts/refs.py all     # check + index + bib

references/pdfs/ is listed in .gitignore: PDFs are never committed. Only
entries with a `pdf_url` (a legal open-access copy) are downloaded.

Standard library only (needs Python 3.11+ for tomllib).
"""

from __future__ import annotations

import argparse
import sys
import time
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF_DIR = ROOT / "references"
TOML_PATH = REF_DIR / "papers.toml"
INDEX_PATH = REF_DIR / "INDEX.md"
BIB_PATH = REF_DIR / "survey.bib"
PDF_DIR = REF_DIR / "pdfs"
PAPER_BIB = ROOT / "paper" / "refs.bib"

REQUIRED = ("key", "section", "title", "authors", "year", "venue", "type", "url", "note")
TYPES = ("article", "inproceedings", "incollection", "book", "techreport", "misc")
PRIORITIES = ("core", "related", "background")
USER_AGENT = "svcc-refs/1.0 (reference library fetcher)"


def load() -> tuple[list[dict], list[dict]]:
    with TOML_PATH.open("rb") as fh:
        data = tomllib.load(fh)
    return data.get("section", []), data.get("paper", [])


def paper_bib_keys() -> set[str]:
    keys = set()
    if PAPER_BIB.exists():
        for line in PAPER_BIB.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith("@") and "{" in line:
                keys.add(line.split("{", 1)[1].rstrip(",").strip())
    return keys


def check(sections: list[dict], papers: list[dict]) -> int:
    errors = []
    section_ids = {s["id"] for s in sections}
    seen = set()
    cited = paper_bib_keys()
    for p in papers:
        key = p.get("key", "<missing key>")
        for field in REQUIRED:
            if field not in p or p[field] in ("", []):
                errors.append(f"{key}: missing `{field}`")
        if key in seen:
            errors.append(f"{key}: duplicate key")
        seen.add(key)
        if p.get("section") not in section_ids:
            errors.append(f"{key}: unknown section `{p.get('section')}`")
        if p.get("type") not in TYPES:
            errors.append(f"{key}: unknown type `{p.get('type')}`")
        if p.get("priority", "related") not in PRIORITIES:
            errors.append(f"{key}: unknown priority `{p.get('priority')}`")
        if p.get("in_paper") and key not in cited:
            errors.append(f"{key}: in_paper = true but key is not in paper/refs.bib")
        if not p.get("in_paper") and key in cited:
            errors.append(f"{key}: key exists in paper/refs.bib, set in_paper = true")
    for err in errors:
        print(f"ERROR {err}", file=sys.stderr)
    print(f"{len(papers)} papers, {len(sections)} sections, {len(errors)} errors")
    return 1 if errors else 0


def short_authors(authors: list[str]) -> str:
    authors = [a.strip("{}") for a in authors]
    if len(authors) <= 3:
        return ", ".join(authors)
    return f"{authors[0]} et al."


def pdf_path(p: dict) -> Path:
    return PDF_DIR / f"{p['key']}.pdf"


def access_cell(p: dict) -> str:
    if p.get("pdf_url"):
        return f"[open PDF]({p['pdf_url']})"
    if p.get("oa_page"):
        return f"[open copy]({p['oa_page']})"
    return "link only"


def write_index(sections: list[dict], papers: list[dict]) -> None:
    n_open = sum(1 for p in papers if p.get("pdf_url"))
    n_page = sum(1 for p in papers if p.get("oa_page") and not p.get("pdf_url"))
    out = [
        "# Related-work index",
        "",
        "<!-- GENERATED by `python3 scripts/refs.py index` from references/papers.toml. Do not edit by hand. -->",
        "",
        f"{len(papers)} entries, {n_open} with a legal open-access PDF "
        "(`python3 scripts/refs.py fetch` saves them to `references/pdfs/<key>.pdf`, which is gitignored). "
        f"A further {n_page} have an *open copy* on an author or repository page. "
        "Entries marked *link only* are paywalled or have no known open copy; follow the link.",
        "",
        "Priority: **core** bears directly on accurate synthesizable design-model conversion, "
        "*related* is adjacent work, and background is context. "
        "A dagger (†) marks entries already cited in `paper/refs.bib`.",
        "",
    ]
    for s in sections:
        rows = [p for p in papers if p["section"] == s["id"]]
        if not rows:
            continue
        order = {name: i for i, name in enumerate(PRIORITIES)}
        rows.sort(key=lambda p: (order[p.get("priority", "related")], -int(p["year"]), p["key"]))
        out += [f"## {s['title']}", "", s.get("blurb", "").strip(), ""]
        out += [
            "| Key | Paper | Year | Venue | Priority | Access | Relevance to svcc |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for p in rows:
            key = f"`{p['key']}`" + ("†" if p.get("in_paper") else "")
            title = f"[{p['title']}]({p['url']})<br>{short_authors(p['authors'])}"
            cells = [
                key,
                title,
                str(p["year"]),
                p["venue"],
                p.get("priority", "related"),
                access_cell(p),
                p["note"],
            ]
            out.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        out.append("")
    INDEX_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {INDEX_PATH.relative_to(ROOT)}")


LATEX_ESCAPES = {
    "&": r"\&",
    "%": r"\%",
    "#": r"\#",
    "_": r"\_",
    "ö": r'{\"o}',
    "ü": r'{\"u}',
    "ä": r'{\"a}',
    "ß": r"{\ss}",
    "é": r"{\'e}",
    "è": r"{\`e}",
    "ê": r"{\^e}",
    "ë": r'{\"e}',
    "ć": r"{\'c}",
    "ž": r"{\v{z}}",
    "ø": r"{\o}",
    "ô": r"{\^o}",
    "ñ": r"{\~n}",
    "ç": r"{\c{c}}",
    "’": "'",
    "‘": "`",
    "–": "--",
    "—": "---",
}


def tex(text: str) -> str:
    return "".join(LATEX_ESCAPES.get(ch, ch) for ch in str(text))


def bib_author(name: str) -> str:
    if name.startswith("{"):
        return name
    parts = name.split()
    if len(parts) == 1:
        return tex(name)
    return f"{tex(parts[-1])}, {tex(' '.join(parts[:-1]))}"


def write_bib(papers: list[dict]) -> None:
    out = [
        "% GENERATED by `python3 scripts/refs.py bib` from references/papers.toml. Do not edit by hand.",
        "% Entries already present in paper/refs.bib (in_paper = true) are omitted, so the two files",
        "% can be loaded together: \\bibliography{refs,../references/survey}",
        "",
    ]
    count = 0
    for p in sorted(papers, key=lambda p: p["key"]):
        if p.get("in_paper"):
            continue
        fields = [("author", " and ".join(bib_author(a) for a in p["authors"]))]
        fields.append(("title", "{" + tex(p["title"]) + "}"))
        kind = p["type"]
        venue = tex(p["venue"])
        if kind == "article":
            fields.append(("journal", venue))
        elif kind in ("inproceedings", "incollection"):
            fields.append(("booktitle", venue))
        elif kind == "techreport":
            fields.append(("institution", venue))
        elif kind == "book":
            fields.append(("publisher", tex(p.get("publisher", p["venue"]))))
        else:
            fields.append(("howpublished", venue))
        for name in ("volume", "number", "pages"):
            if p.get(name):
                fields.append((name, tex(str(p[name]).replace("-", "--") if name == "pages" else p[name])))
        if kind != "book" and p.get("publisher"):
            fields.append(("publisher", tex(p["publisher"])))
        fields.append(("year", str(p["year"])))
        if p.get("doi"):
            fields.append(("doi", p["doi"]))
        if p.get("arxiv"):
            fields.append(("eprint", p["arxiv"]))
            fields.append(("archivePrefix", "arXiv"))
        if not p.get("doi"):
            fields.append(("note", f"\\url{{{p['url']}}}"))
        width = max(len(n) for n, _ in fields)
        out.append(f"@{kind}{{{p['key']},")
        out += [f"  {n.ljust(width)} = {{{v}}}," for n, v in fields]
        out += ["}", ""]
        count += 1
    BIB_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {BIB_PATH.relative_to(ROOT)} ({count} entries)")


def fetch(papers: list[dict], only: list[str], force: bool) -> int:
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    wanted = [p for p in papers if p.get("pdf_url") and (not only or p["key"] in only)]
    ok = skipped = 0
    failed = []
    for p in wanted:
        dest = pdf_path(p)
        if dest.exists() and not force:
            skipped += 1
            continue
        req = urllib.request.Request(p["pdf_url"], headers={"User-Agent": USER_AGENT})
        try:
            with urllib.request.urlopen(req, timeout=90) as resp:
                body = resp.read()
        except (urllib.error.URLError, OSError) as exc:
            failed.append((p["key"], p["pdf_url"], str(exc)))
            continue
        if not body.startswith(b"%PDF"):
            failed.append((p["key"], p["pdf_url"], "response is not a PDF"))
            continue
        dest.write_bytes(body)
        ok += 1
        print(f"saved {dest.relative_to(ROOT)} ({len(body) // 1024} KiB)")
        if "arxiv.org" in p["pdf_url"]:
            time.sleep(3)  # arXiv asks automated clients to pause between requests
    for key, url, why in failed:
        print(f"FAILED {key}: {url} ({why})", file=sys.stderr)
    print(f"{ok} downloaded, {skipped} already present, {len(failed)} failed, of {len(wanted)} open-access entries")
    return 1 if failed else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("check", "index", "bib", "fetch", "all"))
    parser.add_argument("keys", nargs="*", help="fetch: limit to these BibTeX keys")
    parser.add_argument("--force", action="store_true", help="fetch: re-download existing PDFs")
    args = parser.parse_args()
    sections, papers = load()
    if args.command == "check":
        return check(sections, papers)
    if args.command == "index":
        write_index(sections, papers)
        return 0
    if args.command == "bib":
        write_bib(papers)
        return 0
    if args.command == "fetch":
        return fetch(papers, args.keys, args.force)
    status = check(sections, papers)
    if status == 0:
        write_index(sections, papers)
        write_bib(papers)
    return status


if __name__ == "__main__":
    sys.exit(main())
